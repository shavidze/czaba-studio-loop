import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const [base, out] = process.argv.slice(2);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => { try { localStorage.setItem('czaba_lead_magnet', JSON.stringify({ viewCount: 0, lastResetDate: new Date().toISOString().slice(0, 10), dismissed: true, submitted: false })); } catch {} });
const page = await ctx.newPage();
const read = (step) => page.evaluate((s) => { const el = document.querySelector('[data-route-announcer]'); return { step: s, path: location.pathname, title: document.title, region: el ? el.textContent : null, count: document.querySelectorAll('[data-route-announcer]').length, h1: (document.querySelector('.page-transition-wrapper h1')?.textContent || '').trim(), text: document.body.innerText.slice(0, 120) }; }, step);
const res = [];
await page.goto(base + '/faq', { waitUntil: 'networkidle' }).catch(() => {});
await page.waitForTimeout(2500);
await page.waitForFunction(() => !!window.__remixRouter, null, { timeout: 90000 });
res.push(await read('initial /faq'));
await page.evaluate(() => window.__remixRouter.navigate('/studio/middle-east'));
await page.waitForTimeout(4000);
res.push(await read('nav /studio/middle-east'));
fs.writeFileSync(out, JSON.stringify(res, null, 1));
await browser.close();
