import { createRequire } from 'node:module';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const out = process.argv[2];
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
const log = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') log.push(`${m.type()}: ${m.text().slice(0, 160)}`); });
await page.goto('http://127.0.0.1:5173/studio-lab', { waitUntil: 'load', timeout: 60000 });
await page.waitForSelector('[data-testid="arrangement-marker-add"]', { state: 'attached', timeout: 60000 }); await page.waitForTimeout(3000);
const flags = () => page.$$eval('[data-testid="arrangement-marker"]', (els) => els.map((e) => e.getAttribute('data-marker-time')));
const status = () => page.textContent('[data-testid="arrangement-status"]');
await page.click('body', { position: { x: 5, y: 5 } }).catch(() => {});
await page.keyboard.press('Home');
await page.keyboard.press('m');
await page.keyboard.press('Enter');
console.log('after add', await flags());
const flag = page.locator('[data-testid="arrangement-marker"]').first();
const box = await flag.boundingBox();
const pps = await page.evaluate(() => {
  const ruler = document.querySelector('[data-testid="arrangement-marker-strip"]');
  return ruler ? ruler.getBoundingClientRect().width : 0;
});
console.log('box', box, 'strip width', pps);
const x0 = box.x + 3, y0 = box.y + box.height / 2;
const posBefore = await page.evaluate(() => document.querySelector('[data-testid="arrangement-status"]')?.textContent);
await page.mouse.move(x0, y0);
await page.mouse.down();
for (let i = 1; i <= 10; i++) await page.mouse.move(x0 + i * 20, y0);
await page.mouse.up();
console.log('after drag', await flags(), '| status:', await status());
console.log('active is flag:', await page.evaluate(() => document.activeElement?.getAttribute('data-testid')));
await page.keyboard.press('ArrowRight');
console.log('after ArrowRight', await flags(), '| status:', await status());
const f2 = page.locator('[data-testid="arrangement-marker"]').first();
const b2 = await f2.boundingBox();
await page.mouse.click(b2.x + 3, b2.y + b2.height / 2, { button: 'right' });
const menu = await page.$('[data-testid="arrangement-marker-menu"]');
console.log('menu open:', !!menu, menu ? await menu.evaluate((m) => [m.textContent, m.getBoundingClientRect().left, document.activeElement?.textContent]) : null);
await page.screenshot({ path: `${out}/menu.png` });
await page.keyboard.press('Escape');
console.log('after Esc menu:', !!(await page.$('[data-testid="arrangement-marker-menu"]')), 'active:', await page.evaluate(() => document.activeElement?.getAttribute('data-testid')));
await page.keyboard.press('Shift+F10');
console.log('Shift+F10 menu count:', (await page.$$('[data-testid="arrangement-marker-menu"]')).length);
await page.keyboard.press('ArrowDown');
await page.keyboard.press('ArrowDown');
await page.keyboard.press('Enter');
console.log('after menu Delete', await flags(), '| status:', await status());
console.log('console:', log.filter((l) => !/cart|ERR_CONNECTION|ERR_TUNNEL|Failed to load resource/i.test(l)).slice(0, 10));
await browser.close();
