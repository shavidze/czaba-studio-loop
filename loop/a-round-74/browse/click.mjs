import { createRequire } from 'node:module';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
await page.goto('http://127.0.0.1:5173/studio-lab', { waitUntil: 'load', timeout: 60000 });
await page.waitForSelector('[data-testid="arrangement-marker-add"]', { state: 'attached', timeout: 60000 });
await page.waitForTimeout(3000);
const pos = () => page.textContent('[data-testid="arrangement-position"]');
const times = () => page.$$eval('[data-testid="arrangement-marker"]', (els) => els.map((e) => e.getAttribute('data-marker-time')));
await page.keyboard.press('Home');
await page.keyboard.press('m');
await page.keyboard.press('Enter');
await page.click('[data-testid="arrangement-snap-toggle"]');
const flag = page.locator('[data-testid="arrangement-marker"]').first();
let b = await flag.boundingBox();
await page.mouse.move(b.x + 3, b.y + 10); await page.mouse.down();
for (let i = 1; i <= 8; i++) await page.mouse.move(b.x + 3 + i * 12, b.y + 10);
await page.mouse.up();
console.log('snap-on drag ~96px ->', await times(), 'pos', await pos());
b = await flag.boundingBox();
await page.mouse.click(b.x + 3, b.y + 10);
console.log('plain click ->', 'pos', await pos());
await page.keyboard.press('Home');
b = await flag.boundingBox();
await page.mouse.click(b.x + 3, b.y + 10);
await page.mouse.move(b.x + 3, b.y + 10); await page.mouse.down();
for (let i = 1; i <= 4; i++) await page.mouse.move(b.x + 3 + i * 10, b.y + 10);
await page.mouse.up();
await page.waitForTimeout(300);
const playing = await page.getAttribute('[data-testid="arrangement-play"]', 'aria-pressed').catch(() => 'n/a');
console.log('click then quick drag ->', await times(), 'pos', await pos(), 'play pressed', playing);
await browser.close();
