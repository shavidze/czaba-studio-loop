import { createRequire } from 'node:module';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
await ctx.addInitScript(() => { localStorage.setItem('czaba_lead_magnet_dismissed','1'); sessionStorage.setItem('czaba_entrance_seen','1'); });
const page = await ctx.newPage();
await page.route(/googletagmanager|google-analytics/, r => r.abort());
await page.goto('http://127.0.0.1:5174/', { waitUntil: 'domcontentloaded' });
await page.getByRole('button',{name:'Accept',exact:true}).waitFor({timeout:25000});
await page.waitForTimeout(800);
const email = page.locator('input[type=email]').first();
await email.scrollIntoViewIfNeeded(); await email.click();
await page.getByRole('button',{name:'Accept',exact:true}).click();
await page.waitForTimeout(500);
const f = () => page.evaluate(() => { const a=document.activeElement; return [a.tagName,a.getAttribute('aria-label'),(a.textContent||'').trim().slice(0,30)]; });
console.log('after accept', JSON.stringify(await f()));
await page.keyboard.press('Tab');
console.log('after Tab', JSON.stringify(await f()));
