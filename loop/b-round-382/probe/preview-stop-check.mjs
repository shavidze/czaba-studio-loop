import { open, has } from '../../c-round-382/lib.mjs';
import fs from 'node:fs';
const { browser, page, live } = await open('http://127.0.0.1:5173', 1440, 900);
await page.addInitScript(() => {});
await page.evaluate(() => { window.__stops = []; const s = AudioScheduledSourceNode.prototype.stop; AudioScheduledSourceNode.prototype.stop = function (...a) { window.__stops.push({ sec: this.buffer ? +this.buffer.duration.toFixed(2) : null }); return s.apply(this, a); }; });
const btns = async () => page.evaluate(() => [...document.querySelectorAll('button')].filter((b) => /stop|preview|play/i.test((b.getAttribute('aria-label') ?? '') + b.textContent)).map((b) => ({ text: b.textContent.trim().slice(0, 40), aria: b.getAttribute('aria-label'), pressed: b.getAttribute('aria-pressed'), title: b.title?.slice(0, 50) })));
const r = { before: await btns() };
await page.getByRole('button', { name: 'Preview', exact: true }).first().click();
await page.waitForFunction(() => window.__starts.length > 0, null, { timeout: 30000 }).catch(() => {});
await page.waitForTimeout(800);
r.playing = await btns();
const stops = page.getByRole('button', { name: 'Stop', exact: true });
r.stopCount = await stops.count();
r.stopHtml = await stops.first().evaluate((b) => b.outerHTML.slice(0, 300));
await stops.first().click();
await page.waitForTimeout(1500);
r.afterStop = await btns();
r.stops = await page.evaluate(() => window.__stops);
r.live = await live();
fs.writeFileSync('preview-stop-check.json', JSON.stringify(r, null, 1));
await browser.close();
