// B round 397->398: groups at ready, and per-lane [data-clip-id] counts during a held cross-lane name-bar drag (HEAD).
// Usage: node groups-drag.cjs <baseURL> <out.json> [WxH]
const { chromium } = require('/home/runner/czaba-project/store/node_modules/playwright');
const fs = require('node:fs');
const [base, out, vp = '1440x900'] = process.argv.slice(2);
const [w, h] = vp.split('x').map(Number);
const lanes = (page) => page.evaluate(() => [...document.querySelectorAll('[data-track-id]')].map((l) => ({ id: l.getAttribute('data-track-id'), clips: l.querySelectorAll('[data-clip-id]').length, attr: l.getAttribute('data-clip-count'), folded: l.getAttribute('data-track-folded'), top: Math.round(l.getBoundingClientRect().top) })));
(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: w, height: h } });
  await context.addInitScript(() => localStorage.setItem('czaba_analytics_consent', 'denied'));
  const page = await context.newPage();
  await page.goto(base + '/studio-lab', { waitUntil: 'load', timeout: 180000 });
  await page.getByTestId('arrangement-status').filter({ hasText: /Demo collection ready/ }).waitFor({ timeout: 120000 });
  await page.waitForTimeout(1000);
  const r = { vp };
  r.groupsAtReady = await page.evaluate(() => ({ groups: document.querySelectorAll('[data-group-id]').length, ids: [...document.querySelectorAll('[data-group-id]')].map((g) => g.getAttribute('data-group-id')).slice(0, 10) }));
  r.lanesAtReady = await lanes(page);
  await page.getByRole('button', { name: 'Add', exact: true }).click();
  await page.locator('[data-clip-kind="audio"]').first().waitFor();
  await page.waitForTimeout(500);
  const clip = page.locator('[data-clip-kind="audio"]').first();
  r.addedLane = await clip.evaluate((c) => c.closest('[data-track-id]')?.getAttribute('data-track-id'));
  const bar = clip.getByTitle(/ — drag to move$/).first();
  const box = await bar.boundingBox();
  await page.mouse.click(box.x + 20, box.y + box.height / 2);
  await page.evaluate(() => document.activeElement instanceof HTMLElement && document.activeElement.blur());
  for (let i = 0; i < 2; i += 1) await page.keyboard.press('Control+d');
  await page.waitForTimeout(500);
  r.afterDup = await lanes(page);
  const all = r.afterDup;
  const src = all.findIndex((l) => l.id === r.addedLane);
  const target = all.slice(src + 1).find((l) => l.folded !== 'true') ?? all[src - 1];
  r.target = target?.id;
  const sx = box.x + 20, sy = box.y + box.height / 2;
  const dy = (target.top + 30) - sy;
  await page.mouse.move(sx, sy);
  await page.mouse.down();
  for (let s = 1; s <= 10; s += 1) await page.mouse.move(sx + 5 * s, sy + (dy * s) / 10);
  await page.waitForTimeout(400);
  r.held = await lanes(page);
  r.heldGhosts = await page.evaluate(() => document.querySelectorAll('[data-clip-kind]').length);
  await page.mouse.up();
  await page.waitForTimeout(500);
  r.released = await lanes(page);
  await page.keyboard.press('Control+z');
  await page.waitForTimeout(500);
  r.undone = await lanes(page);
  r.status = await page.getByTestId('arrangement-status').textContent();
  fs.writeFileSync(out, JSON.stringify(r, null, 1));
  const brief = (ls) => ls.map((l) => `${l.id}:${l.clips}`).join(' ');
  console.log(vp, 'groups', JSON.stringify(r.groupsAtReady), 'added', r.addedLane, 'target', r.target, '| dup', brief(r.afterDup), '| held', brief(r.held), '| released', brief(r.released), '| undo', brief(r.undone));
  await browser.close();
})();
