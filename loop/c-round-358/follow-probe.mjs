import { chromium } from '/home/runner/czaba-project/store/node_modules/playwright/index.mjs';
import { writeFileSync } from 'node:fs';
const base = process.argv[2]; const out = process.argv[3];
const [W, H] = (process.argv[4] ?? '1440x900').split('x').map(Number);
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const ctx = await browser.newContext({ viewport: { width: W, height: H } });
await ctx.addInitScript(() => localStorage.setItem('czaba_analytics_consent', 'denied'));
const page = await ctx.newPage();
const st = () => page.evaluate(() => document.querySelector('[data-testid="arrangement-status"]')?.textContent ?? null);
const pl = () => page.evaluate(() => document.querySelector('[data-playing]')?.getAttribute('data-playing') ?? null);
const sl = () => page.evaluate(() => document.querySelector('[data-testid="arrangement-timeline-scroller"]')?.scrollLeft ?? null);
const sp = async () => { await page.evaluate(() => document.activeElement?.blur?.()); await page.keyboard.press('Space'); };
const fb = () => page.getByTestId('arrangement-follow').evaluate(e => ({ dashed: e.className.includes('dashed'), pressed: e.getAttribute('aria-pressed') }));
const R = { base, vp: `${W}x${H}` };
await page.goto(`${base}/studio-lab`, { waitUntil: 'load', timeout: 120000 });
await page.waitForFunction(() => /ready/i.test(document.querySelector('[data-testid="arrangement-status"]')?.textContent ?? ''), null, { timeout: 120000 });
await page.waitForTimeout(1000);
await page.getByText('Full mix', { exact: true }).first().click(); await page.keyboard.press('Enter');
await page.locator('[data-clip-kind="audio"]').first().waitFor(); await page.waitForTimeout(1500);
await page.evaluate(() => document.activeElement?.blur?.());
for (let i = 0; i < 8; i++) { await page.keyboard.press('='); await page.waitForTimeout(250); }
R.zoomed = { sl: await sl(), status: await st() };
await sp(); await page.waitForTimeout(500);
R.play0 = { playing: await pl(), sl: await sl(), follow: await fb() };
await page.waitForTimeout(7000);
R.play1 = { playing: await pl(), sl: await sl() };
await page.evaluate(() => { const e = document.querySelector('[data-testid="arrangement-timeline-scroller"]'); e.scrollLeft = Math.max(0, e.scrollLeft - 300); });
await page.mouse.move(W / 2, H / 2); await page.mouse.wheel(-200, 0); await page.waitForTimeout(900);
R.manual = { playing: await pl(), status: await st(), follow: await fb(), sl: await sl() };
await sp(); await page.waitForTimeout(700);
R.stop = { playing: await pl(), status: await st(), follow: await fb() };
await page.screenshot({ path: out.replace(/\.json$/, '.png') });
writeFileSync(out, JSON.stringify(R, null, 1));
await browser.close();
