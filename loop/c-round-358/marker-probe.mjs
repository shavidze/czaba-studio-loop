import { chromium } from '/home/runner/czaba-project/store/node_modules/playwright/index.mjs';
import { writeFileSync } from 'node:fs';
const base = process.argv[2]; const out = process.argv[3];
const [W, H] = (process.argv[4] ?? '1440x900').split('x').map(Number);
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const ctx = await browser.newContext({ viewport: { width: W, height: H } });
await ctx.addInitScript(() => localStorage.setItem('czaba_analytics_consent', 'denied'));
const page = await ctx.newPage();
const st = () => page.evaluate(() => document.querySelector('[data-testid="arrangement-status"]')?.textContent ?? null);
const pl = () => page.evaluate(() => document.querySelector('[data-playing]')?.getAttribute('data-playing') ?? null);
const sp = async () => { await page.evaluate(() => document.activeElement?.blur?.()); await page.keyboard.press('Space'); await page.waitForTimeout(700); };
const R = { vp: `${W}x${H}` };
await page.goto(`${base}/studio-lab`, { waitUntil: 'load', timeout: 150000 });
await page.waitForFunction(() => /ready/i.test(document.querySelector('[data-testid="arrangement-status"]')?.textContent ?? ''), null, { timeout: 150000 });
await page.waitForTimeout(1000);
await page.getByText('Full mix', { exact: true }).first().click(); await page.keyboard.press('Enter');
await page.locator('[data-clip-kind="audio"]').first().waitFor(); await page.waitForTimeout(1500);
R.next = await page.getByTestId('arrangement-marker-next').evaluate(e => ({ disabled: e.disabled, aria: e.getAttribute('aria-disabled') }));
R.playing0 = (await sp(), await pl());
await page.getByTestId('arrangement-marker-next').click({ force: true }); await page.waitForTimeout(500);
R.nextWhilePlaying = { playing: await pl(), status: await st() };
await sp(); R.stopped = await pl();
await page.getByTestId('arrangement-marker-next').click({ force: true }); await page.waitForTimeout(500);
R.nextWhileStopped = { playing: await pl(), status: await st() };
await page.getByTestId('arrangement-marker-prev').click({ force: true }); await page.waitForTimeout(500);
R.prevWhileStopped = await st();
writeFileSync(out, JSON.stringify(R, null, 1)); await browser.close();
