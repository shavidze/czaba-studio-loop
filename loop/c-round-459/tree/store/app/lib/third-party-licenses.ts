const LICENSE_ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9.-]*\+?$/;
const COPYLEFT_ID_PATTERN = /^A?GPL(?:V?\d|[-+]|$)/i;
const LICENSE_REF_PATTERN = /^LicenseRef-/i;
const NOT_A_LICENSE_IDS = new Set(['UNLICENSED']);

type SpdxToken = '(' | ')' | 'AND' | 'OR' | 'WITH' | { id: string };

function tokenizeSpdxExpression(expression: string): SpdxToken[] {
  const tokens: SpdxToken[] = [];
  const words = expression.replace(/\(/g, ' ( ').replace(/\)/g, ' ) ').split(/\s+/);
  for (const word of words) {
    if (word === '') {
      continue;
    }
    const upper = word.toUpperCase();
    if (word === '(' || word === ')') {
      tokens.push(word);
    } else if (upper === 'AND' || upper === 'OR' || upper === 'WITH') {
      tokens.push(upper);
    } else {
      tokens.push({ id: word });
    }
  }
  return tokens;
}

function classifyLicenseId(id: string): LicenseClassification {
  if (
    !LICENSE_ID_PATTERN.test(id) ||
    NOT_A_LICENSE_IDS.has(id.toUpperCase()) ||
    LICENSE_REF_PATTERN.test(id)
  ) {
    return 'unknown';
  }
  return COPYLEFT_ID_PATTERN.test(id) ? 'copyleft' : 'clean';
}

function combineOrClassifications(parts: LicenseClassification[]): LicenseClassification {
  if (parts.includes('clean')) {
    return 'clean';
  }
  return parts.includes('unknown') ? 'unknown' : 'copyleft';
}

function combineAndClassifications(parts: LicenseClassification[]): LicenseClassification {
  if (parts.includes('copyleft')) {
    return 'copyleft';
  }
  return parts.includes('unknown') ? 'unknown' : 'clean';
}

class SpdxExpressionParser {
  private position = 0;

  constructor(private readonly tokens: SpdxToken[]) {}

  parseWhole(): LicenseClassification | null {
    const result = this.parseOr();
    if (result === null || this.position !== this.tokens.length) {
      return null;
    }
    return result;
  }

  private parseOr(): LicenseClassification | null {
    const parts: LicenseClassification[] = [];
    do {
      const part = this.parseAnd();
      if (part === null) {
        return null;
      }
      parts.push(part);
    } while (this.consumeOperator('OR'));
    return combineOrClassifications(parts);
  }

  private parseAnd(): LicenseClassification | null {
    const parts: LicenseClassification[] = [];
    do {
      const part = this.parseWith();
      if (part === null) {
        return null;
      }
      parts.push(part);
    } while (this.consumeOperator('AND'));
    return combineAndClassifications(parts);
  }

  private parseWith(): LicenseClassification | null {
    const primary = this.parsePrimary();
    if (primary === null) {
      return null;
    }
    if (this.consumeOperator('WITH')) {
      const exceptionToken = this.tokens[this.position];
      if (exceptionToken === undefined || typeof exceptionToken === 'string') {
        return null;
      }
      if (!LICENSE_ID_PATTERN.test(exceptionToken.id)) {
        return null;
      }
      this.position += 1;
    }
    return primary;
  }

  private parsePrimary(): LicenseClassification | null {
    const token = this.tokens[this.position];
    if (token === undefined) {
      return null;
    }
    if (token === '(') {
      this.position += 1;
      const inner = this.parseOr();
      if (inner === null || this.tokens[this.position] !== ')') {
        return null;
      }
      this.position += 1;
      return inner;
    }
    if (typeof token === 'string') {
      return null;
    }
    this.position += 1;
    return classifyLicenseId(token.id);
  }

  private consumeOperator(operator: 'AND' | 'OR' | 'WITH'): boolean {
    if (this.tokens[this.position] === operator) {
      this.position += 1;
      return true;
    }
    return false;
  }
}

export function classifyLicenseExpression(expression: string): LicenseClassification {
  const tokens = tokenizeSpdxExpression(expression);
  if (tokens.length === 0) {
    return 'unknown';
  }
  return new SpdxExpressionParser(tokens).parseWhole() ?? 'unknown';
}

export function readLicenseFieldText(field: unknown): string | null {
  let text: unknown = field;
  if (typeof field === 'object' && field !== null && 'type' in field) {
    text = field.type;
  }
  return typeof text === 'string' && text.trim() !== '' ? text : null;
}

export function classifyLicenseField(field: unknown): LicenseClassification {
  const text = readLicenseFieldText(field);
  return text === null ? 'unknown' : classifyLicenseExpression(text);
}

function isPlainRecord(value: unknown): value is object {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function readStringProperty(record: object, key: string): string | null {
  const value: unknown = Reflect.get(record, key);
  return typeof value === 'string' ? value : null;
}

function readTrueProperty(record: object, key: string): boolean {
  return Reflect.get(record, key) === true;
}

function packageNameFromLockPath(lockPath: string): string {
  const marker = 'node_modules/';
  const index = lockPath.lastIndexOf(marker);
  return index === -1 ? lockPath : lockPath.slice(index + marker.length);
}

function compareCodePoints(left: string, right: string): number {
  if (left < right) {
    return -1;
  }
  return left > right ? 1 : 0;
}

function runtimePackageKey(name: string, version: string): string {
  return `${name}@${version}`;
}

function compareRuntimeLockPackages(left: RuntimeLockPackage, right: RuntimeLockPackage): number {
  return (
    compareCodePoints(left.name, right.name) ||
    compareCodePoints(left.version, right.version) ||
    compareCodePoints(left.lockPath, right.lockPath)
  );
}

function readLockEntryKind(entry: object): RuntimeLockPackage['lockEntryKind'] {
  if (readTrueProperty(entry, 'link')) {
    return 'link';
  }
  return readTrueProperty(entry, 'inBundle') ? 'inBundle' : null;
}

export function listRuntimeLockEntries(lock: unknown): RuntimeLockPackage[] {
  if (!isPlainRecord(lock)) {
    return [];
  }
  const packages: unknown = Reflect.get(lock, 'packages');
  if (!isPlainRecord(packages)) {
    return [];
  }
  const entries: [string, unknown][] = Object.entries(packages);
  const runtimeEntries: RuntimeLockPackage[] = [];
  for (const [lockPath, entry] of entries) {
    if (lockPath === '' || !isPlainRecord(entry) || readTrueProperty(entry, 'dev')) {
      continue;
    }
    runtimeEntries.push({
      name: readStringProperty(entry, 'name') ?? packageNameFromLockPath(lockPath),
      version: readStringProperty(entry, 'version') ?? '',
      license: readLicenseFieldText(Reflect.get(entry, 'license')),
      lockPath,
      lockEntryKind: readLockEntryKind(entry),
    });
  }
  return runtimeEntries.sort(compareRuntimeLockPackages);
}

export function listRuntimeLockPackages(lock: unknown): RuntimeLockPackage[] {
  const seen = new Set<string>();
  return listRuntimeLockEntries(lock).filter((runtimeEntry) => {
    const key = runtimePackageKey(runtimeEntry.name, runtimeEntry.version);
    if (seen.has(key)) {
      return false;
    }
    seen.add(key);
    return true;
  });
}

export function classifyRuntimeLockPackage(
  runtimePackage: RuntimeLockPackage,
): LicenseClassification {
  if (runtimePackage.lockEntryKind !== null || runtimePackage.license === null) {
    return 'unknown';
  }
  return classifyLicenseExpression(runtimePackage.license);
}

function findMatchingLicenseException(
  runtimePackage: RuntimeLockPackage,
  exceptions: readonly ThirdPartyLicenseException[],
): ThirdPartyLicenseException | undefined {
  return exceptions.find(
    (exception) =>
      exception.name === runtimePackage.name && exception.version === runtimePackage.version,
  );
}

function isCoveredByLicenseException(
  runtimePackage: RuntimeLockPackage,
  exceptions: readonly ThirdPartyLicenseException[],
): boolean {
  return (
    runtimePackage.lockEntryKind === null &&
    runtimePackage.license === null &&
    findMatchingLicenseException(runtimePackage, exceptions) !== undefined
  );
}

export function findCopyleftRuntimePackages(
  lock: unknown,
  exceptions: readonly ThirdPartyLicenseException[],
): CopyleftRuntimeReport {
  const runtimeEntries = listRuntimeLockEntries(lock);
  const failures: CopyleftRuntimeFinding[] = [];
  for (const runtimePackage of runtimeEntries) {
    const classification = classifyRuntimeLockPackage(runtimePackage);
    if (classification === 'clean' || isCoveredByLicenseException(runtimePackage, exceptions)) {
      continue;
    }
    failures.push({
      name: runtimePackage.name,
      version: runtimePackage.version,
      license: runtimePackage.license,
      lockPath: runtimePackage.lockPath,
      classification,
    });
  }
  const staleExceptions: StaleLicenseException[] = [];
  for (const exception of exceptions) {
    const matches = runtimeEntries.filter(
      (runtimePackage) =>
        runtimePackage.name === exception.name && runtimePackage.version === exception.version,
    );
    if (matches.length === 0) {
      staleExceptions.push({
        name: exception.name,
        version: exception.version,
        reason: 'no-runtime-entry',
      });
    } else if (matches.some((runtimePackage) => runtimePackage.license !== null)) {
      staleExceptions.push({
        name: exception.name,
        version: exception.version,
        reason: 'entry-has-license',
      });
    }
  }
  return { failures, staleExceptions };
}

export function findThirdPartySourceLink(packageName: string): string | null {
  const link = THIRD_PARTY_SOURCE_LINKS.find((candidate) =>
    candidate.matchPrefix
      ? packageName.startsWith(candidate.packageName)
      : packageName === candidate.packageName,
  );
  return link === undefined ? null : link.sourceUrl;
}

export function isMplLicensedRuntimePackage(runtimePackage: RuntimeLockPackage): boolean {
  if (runtimePackage.license === null) {
    return false;
  }
  return tokenizeSpdxExpression(runtimePackage.license).some(
    (token) => typeof token !== 'string' && token.id.toUpperCase() === 'MPL-2.0',
  );
}

function escapeTableCell(value: string): string {
  return value.replace(/\|/g, '\\|');
}

function renderLicenseCell(
  runtimePackage: RuntimeLockPackage,
  exceptions: readonly ThirdPartyLicenseException[],
): string {
  if (isCoveredByLicenseException(runtimePackage, exceptions)) {
    const exception = findMatchingLicenseException(runtimePackage, exceptions);
    if (exception !== undefined) {
      return `${exception.assertedLicense} (asserted; see exceptions)`;
    }
  }
  return runtimePackage.license ?? '(no usable license field in lock)';
}

function renderMplSourcesSection(runtimePackages: RuntimeLockPackage[]): string {
  const names = [
    ...new Set(runtimePackages.filter(isMplLicensedRuntimePackage).map((item) => item.name)),
  ].sort(compareCodePoints);
  const lines = names.map(
    (name) => `- \`${name}\`: ${findThirdPartySourceLink(name) ?? '(no source link recorded)'}`,
  );
  return [NOTICES_MPL_SECTION_INTRO, '', ...lines].join('\n');
}

function renderExceptionsSection(exceptions: readonly ThirdPartyLicenseException[]): string {
  const lines = [...exceptions]
    .sort(
      (left, right) =>
        compareCodePoints(left.name, right.name) || compareCodePoints(left.version, right.version),
    )
    .map(
      (exception) =>
        `- \`${exception.name}@${exception.version}\`: asserted ${exception.assertedLicense}. ${exception.reason}.`,
    );
  return [
    '## License exceptions',
    '',
    'Runtime packages whose lock entry has no usable license field, with the license checked by hand:',
    '',
    ...lines,
  ].join('\n');
}

function renderPackagesTable(
  runtimePackages: RuntimeLockPackage[],
  exceptions: readonly ThirdPartyLicenseException[],
): string {
  const rows = runtimePackages.map((runtimePackage) =>
    [
      '',
      escapeTableCell(runtimePackage.name),
      escapeTableCell(runtimePackage.version),
      escapeTableCell(renderLicenseCell(runtimePackage, exceptions)),
      `https://www.npmjs.com/package/${runtimePackage.name}/v/${runtimePackage.version}`,
      '',
    ]
      .join(' | ')
      .trim(),
  );
  return [
    `## Runtime packages (${runtimePackages.length})`,
    '',
    '| Package | Version | License | Link |',
    '|---|---|---|---|',
    ...rows,
  ].join('\n');
}

export function renderThirdPartyNotices(
  lock: unknown,
  exceptions: readonly ThirdPartyLicenseException[] = THIRD_PARTY_LICENSE_EXCEPTIONS,
): string {
  const runtimePackages = listRuntimeLockPackages(lock);
  const sections = [
    NOTICES_INTRO_SECTION,
    NOTICES_LAME_SECTION,
    NOTICES_FONTS_SECTION,
    renderMplSourcesSection(runtimePackages),
    renderExceptionsSection(exceptions),
    renderPackagesTable(runtimePackages, exceptions),
  ];
  return `${sections.join('\n\n')}\n`;
}
