export type LicenseClassification = 'clean' | 'copyleft' | 'unknown';

export interface RuntimeLockPackage {
  name: string;
  version: string;
  license: string | null;
  lockPath: string;
  lockEntryKind: 'link' | 'inBundle' | null;
}

export interface ThirdPartyLicenseException {
  name: string;
  version: string;
  assertedLicense: string;
  reason: string;
}

export interface CopyleftRuntimeFinding {
  name: string;
  version: string;
  license: string | null;
  lockPath: string;
  classification: LicenseClassification;
}

export interface StaleLicenseException {
  name: string;
  version: string;
  reason: 'no-runtime-entry' | 'entry-has-license';
}

export interface CopyleftRuntimeReport {
  failures: CopyleftRuntimeFinding[];
  staleExceptions: StaleLicenseException[];
}

export interface ThirdPartySourceLink {
  packageName: string;
  matchPrefix: boolean;
  sourceUrl: string;
}

