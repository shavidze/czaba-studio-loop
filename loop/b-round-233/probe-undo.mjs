import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage();
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://127.0.0.1:5173/studio-lab', { waitUntil: 'networkidle' });
await page.waitForFunction(() => { const add = [...document.querySelectorAll('button')].find((b) => /^Add/.test(b.textContent.trim())); return add && !add.disabled; }, undefined, { timeout: 90000 });
await page.waitForTimeout(800);
await page.locator('[data-source-id="demo-stem-pulse"]').first().click();
await page.locator('button', { hasText: /^Add/ }).first().click(); await page.waitForTimeout(600);
const res = { afterAdd: await page.locator('[data-clip-id]').count(), focused: await page.evaluate(() => document.activeElement?.getAttribute('data-testid') || document.activeElement?.tagName) };
await page.keyboard.press('Control+z'); await page.waitForTimeout(500);
res.afterUndo = await page.locator('[data-clip-id]').count();
res.status = await page.locator('[data-testid="arrangement-status"]').textContent();
res.errors = errors;
await browser.close();
writeFileSync(process.argv[2], JSON.stringify(res, null, 1)); console.log(JSON.stringify(res));
