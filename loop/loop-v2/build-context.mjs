// Builds a small "active" view of the loop's planning state so agents do not load the whole history.
// Input: <loopRoot>/backlog.json (B owns it; this script only reads it). Output: <loopRoot>/context/*.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2] ?? 'C:/Apps/czaba-project/tmp/studio-real-loop';
const read = (p) => {
  const b = readFileSync(p);
  if (b[0] === 0xff && b[1] === 0xfe) return b.toString('utf16le').replace(/^\uFEFF/, '');
  return b.toString('utf8').replace(/^\uFEFF/, '');
};
const closed = /^(closed|resolved|done|accepted|recorded|superseded|merged|not a bug|fixed|verified)/i;
const isOpen = (x) => !closed.test(String(x?.status ?? ''));
const backlog = JSON.parse(read(join(root, 'backlog.json')));
const latestNumbered = (prefix) => {
  const keys = Object.keys(backlog).filter((k) => k.startsWith(prefix)).map((k) => [k, Number(k.slice(prefix.length))]).filter(([, n]) => Number.isFinite(n));
  keys.sort((a, b) => b[1] - a[1]);
  return keys.length ? { [keys[0][0]]: backlog[keys[0][0]] } : {};
};
const clip = (v, n = 1500) => {
  if (typeof v === 'string') return v.length > n ? `${v.slice(0, n)} ... [clipped; full text in backlog.json]` : v;
  if (Array.isArray(v)) return v.map((x) => clip(x, n));
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, clip(x, n)]));
  return v;
};
const taskHead = existsSync(join(root, 'current-task.md')) ? read(join(root, 'current-task.md')).split('\n').slice(0, 40).join('\n') : String(backlog.current_task ?? '');
const counts = {};
for (const m of taskHead.matchAll(/SRW-\d+[A-Z]?/g)) counts[m[0]] = (counts[m[0]] ?? 0) + 1;
const currentIds = new Set(Object.entries(counts).sort((a, b) => b[1] - a[1]).slice(0, 2).map(([k]) => k));
const rounds = Array.isArray(backlog.rounds) ? backlog.rounds : [];
const currentRound = rounds.length ? Math.max(...rounds.map((r) => Number(r.round) || 0)) : 0;
const active = {
  _about: 'Generated by loop-v2/build-context.mjs from backlog.json. Read-only view; B still edits backlog.json. Look up anything else by ID with grep in backlog.json.',
  _generatedUtc: new Date().toISOString(),
  version: backlog.version,
  current_task: backlog.current_task,
  done_policy: backlog.done_policy,
  global_forbidden_files: backlog.global_forbidden_files,
  global_forbidden_actions: backlog.global_forbidden_actions,
  protocol: backlog.protocol,
  workflow_policy: backlog.workflow_policy,
  harness_rules: backlog.harness_rules,
  narrow_grants: (backlog.narrow_grants ?? []).filter((g) => Number(g.round) >= currentRound - 1),
  current_items_full: (backlog.items ?? []).filter((i) => currentIds.has(String(i.id))).map(({ evidence, ...rest }) => clip(rest)),
  items_in_progress: (backlog.items ?? []).filter((i) => !['done', 'todo'].includes(String(i.status)) && !currentIds.has(String(i.id))).map((i) => ({ id: i.id, title: i.title, status: i.status, fb: i.fb, open_bugs: Array.isArray(i.open_bugs) ? i.open_bugs.map((b) => (typeof b === 'object' ? `${b.id ?? ''} ${b.status ?? ''}`.trim() : String(b).slice(0, 80))) : undefined })),
  items_todo: (backlog.items ?? []).filter((i) => String(i.status) === 'todo').map(({ id, title, status, fb, depends_on, round }) => ({ id, title, status, fb, depends_on, round })),
  open_findings: (backlog.open_findings ?? []).filter(isOpen).map((f) => clip(f, 600)),
  open_tech_lead_checks: (backlog.tech_lead_manual_checks ?? []).filter((c) => String(c.status ?? '') === 'open'),
  recent_rounds: rounds.slice(-3),
  upcoming_planned_rounds: (backlog.planned_rounds ?? []).filter((p) => !p.status || !closed.test(String(p.status))).slice(0, 8),
  post_current_stage_queue: backlog.post_current_stage_queue,
  recent_architecture_signals: (backlog.architecture_signals ?? []).slice(-5),
  ...latestNumbered('baseline_tree_at_round'),
  ...latestNumbered('vitest_floor_round'),
  ...latestNumbered('vitest_expected_round'),
  other_top_level_keys: Object.keys(backlog).filter((k) => !/^(baseline_tree_at_round|vitest_floor_round|vitest_expected_round)\d+$/.test(k)),
};
mkdirSync(join(root, 'context'), { recursive: true });
const activeText = JSON.stringify(active, null, 2);
writeFileSync(join(root, 'context', 'active-backlog.json'), activeText);

const lines = [];
lines.push(`# Active loop summary (generated ${active._generatedUtc})`, '');
lines.push(`- backlog.json: ${(read(join(root, 'backlog.json')).length / 1024).toFixed(0)} KB full -> active view ${(activeText.length / 1024).toFixed(0)} KB`);
lines.push(`- latest round in backlog: ${currentRound}; current ${[...currentIds].join('+') || '-'}; other in progress: ${active.items_in_progress.length}, todo: ${active.items_todo.length}; open findings: ${active.open_findings.length}; open Tech Lead checks: ${active.open_tech_lead_checks.length}`);
const status = existsSync(join(root, 'status.json')) ? JSON.parse(read(join(root, 'status.json'))) : null;
if (status) lines.push(`- loop status: ${status.phase} round ${status.round} (${status.updatedUtc})`);
for (const f of ['env-status.json', 'loop-v2/last-publication.json']) {
  if (existsSync(join(root, f))) lines.push(`- ${f}: \`${read(join(root, f)).replace(/\s+/g, ' ').slice(0, 300)}\``);
}
const gates = existsSync(join(root, 'loop-v2', 'gates')) ? readdirSync(join(root, 'loop-v2', 'gates')).filter((f) => /^gate-round-\d+\.json$/.test(f)).sort((a, b) => Number(a.match(/\d+/)[0]) - Number(b.match(/\d+/)[0])) : [];
if (gates.length) {
  const g = JSON.parse(read(join(root, 'loop-v2', 'gates', gates[gates.length - 1])));
  lines.push(`- last root gate: round ${g.round} ${g.status} - ${g.reason}`);
}
lines.push('', '## Open findings (id / severity / status / title)');
for (const f of active.open_findings) lines.push(`- ${f.id} / ${f.severity ?? '-'} / ${f.status} / ${String(f.title ?? f.note ?? '').slice(0, 140)}`);
lines.push('', `## Current items (full detail): ${[...currentIds].join(', ') || '-'}`, '', '## Other items in progress / open');
for (const i of active.items_in_progress) lines.push(`- ${i.id} [${i.status}] ${String(i.title ?? '').slice(0, 140)}`);
lines.push('', '## Items todo');
for (const i of active.items_todo) lines.push(`- ${i.id} [${i.status}] ${String(i.title ?? '').slice(0, 140)}`);
writeFileSync(join(root, 'context', 'active-summary.md'), lines.join('\n') + '\n');
console.log(`context: active ${(activeText.length / 1024).toFixed(0)} KB, findings ${active.open_findings.length}, items ${active.items_in_progress.length}+${active.items_todo.length}`);
