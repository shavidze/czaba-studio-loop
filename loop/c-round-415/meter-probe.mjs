import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const [w,h]=[+process.argv[2],+process.argv[3]];
const out={viewport:[w,h],errors:[]};
const b=await chromium.launch({args:['--autoplay-policy=no-user-gesture-required']});
const ctx=await b.newContext({viewport:{width:w,height:h}});
const p=await ctx.newPage();
p.on('pageerror',e=>out.errors.push('pageerror:'+e.message));
p.on('console',m=>{if(m.type()==='error')out.errors.push('console:'+m.text().slice(0,140))});
await p.goto('http://127.0.0.1:5173/studio-lab',{waitUntil:'networkidle'});
await p.getByText('Demo collection ready').first().waitFor({timeout:20000}).catch(()=>out.noReady=true);
await p.waitForTimeout(1000);
out.clipsBefore=await p.locator('[data-testid*="clip"]').count();
const meter=p.locator('[data-testid=arrangement-master-meter]');
out.meterCount=await meter.count();
const rd=async()=>({l:await meter.getAttribute('data-level-db'),h:await meter.getAttribute('data-hold-db')});
out.idle=await rd();
out.testids=await p.evaluate(()=>[...new Set([...document.querySelectorAll('[data-testid]')].map(e=>e.dataset.testid))].slice(0,80));
await p.screenshot({path:`c-round-415/meter-idle-${w}.png`});
out.clipTestids=await p.evaluate(()=>[...document.querySelectorAll('[data-testid*="clip"]')].map(e=>e.dataset.testid));
await p.getByText('Full mix',{exact:true}).first().click();
await p.getByRole('button',{name:/Add/}).first().click();
await p.waitForTimeout(1500);
out.statusAfterAdd=await p.locator('[role=status]').first().textContent().catch(()=>null);
out.clipTestids2=await p.evaluate(()=>[...document.querySelectorAll('[data-testid^="arrangement-clip"]')].length);
await p.mouse.click(900,780);
await p.waitForTimeout(200);
await p.keyboard.press('Space');
await p.waitForTimeout(1000);
out.playState=await p.getByTestId('arrangement-playback-state').textContent();
out.samples=[];
for(let i=0;i<10;i++){out.samples.push(await rd());await p.waitForTimeout(100);}
out.holdBox=await meter.locator(':scope > *').last().boundingBox();
out.trackLevels=await p.locator('[data-testid=arrangement-track-meter]').evaluateAll(es=>es.map(e=>e.dataset.levelDb));
await p.screenshot({path:`c-round-415/meter-playing-${w}.png`});
await p.keyboard.press('Space');
const t0=Date.now();let stopped=null;
while(Date.now()-t0<2000){const r=await rd();const tl=await p.locator('[data-testid=arrangement-track-meter]').evaluateAll(es=>es.map(e=>e.dataset.levelDb));if(r.l==='-inf'&&r.h==='-inf'&&tl.every(x=>x==='-inf')){stopped=Date.now()-t0;break;}await p.waitForTimeout(25);}
out.stopMs=stopped;
out.playStateAfter=await p.getByTestId('arrangement-playback-state').textContent();
await p.screenshot({path:`c-round-415/meter-stopped-${w}.png`});
writeFileSync(`c-round-415/meter-${w}.json`,JSON.stringify(out,null,1));
await b.close();console.log(JSON.stringify(out));
