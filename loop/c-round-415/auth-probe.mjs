import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const out = { at: new Date().toISOString() };
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: +process.argv[2], height: +process.argv[3] } });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:5173/studio-lab', { waitUntil: 'networkidle' });
await p.waitForTimeout(1500);
out.lab = { authUser: await p.evaluate(() => localStorage.getItem('auth_user')), signInRequired: await p.getByText('Sign in required').count(), audioSrc: await p.locator('audio[src]').count(), url: p.url() };
await p.screenshot({ path: 'c-round-415/auth-lab-'+process.argv[2]+'.png' });
const q = await ctx.newPage();
await q.goto('http://127.0.0.1:5173/studio/middle-east', { waitUntil: 'networkidle' });
await q.waitForTimeout(1500);
out.premium = { url: q.url(), signInRequired: await q.getByText('Sign in required').count(), audioSrc: await q.locator('audio[src]').count(), authUser: await q.evaluate(() => localStorage.getItem('auth_user')) };
await q.screenshot({ path: 'c-round-415/auth-premium-'+process.argv[2]+'.png' });
const r = await ctx.request.get('http://127.0.0.1:5173/api/studio-token?product=middle-east&file=a.mp3');
out.token = { status: r.status() };
writeFileSync('c-round-415/auth-'+process.argv[2]+'.json', JSON.stringify(out, null, 1));
await b.close();
console.log(JSON.stringify(out));
