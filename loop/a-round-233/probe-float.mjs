import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const base = process.argv[2] || 'http://127.0.0.1:5173';
const out = process.argv[3] || 'probe';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const res = {};
const id = (page) => page.evaluate(() => { const a = document.activeElement; return { id: a?.getAttribute('data-testid') || a?.tagName, fv: a ? a.matches(':focus-visible') : false, outline: a ? getComputedStyle(a).outlineStyle + ' ' + getComputedStyle(a).outlineWidth : null }; });
for (const [w, h] of [[1440, 900], [1280, 720]]) {
  const ctx = await browser.newContext({ viewport: { width: w, height: h } });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto(`${base}/studio-lab`, { waitUntil: 'networkidle' });
  await page.waitForFunction(() => { const add = [...document.querySelectorAll('button')].find((b) => /^Add/.test(b.textContent.trim())); return add && !add.disabled; }, undefined, { timeout: 120000 });
  await page.waitForTimeout(800);
  const r = {};
  await page.focus('[data-testid="arrangement-library-separator"]'); await page.keyboard.press('Tab');
  await page.keyboard.press('Control+Alt+KeyO'); await page.waitForTimeout(300);
  r.dockedHide = await id(page);
  await page.screenshot({ path: `${out}/a-docked-hide-${w}x${h}.png` });
  await page.keyboard.press('Control+Alt+KeyO'); await page.waitForTimeout(300);
  await page.click('[data-testid="arrangement-video-expand"]'); await page.waitForTimeout(500);
  await page.focus('[data-testid="arrangement-library-separator"]'); await page.keyboard.press('Tab');
  r.floatOverviewFocused = await id(page);
  await page.keyboard.press('Control+Alt+KeyO'); await page.waitForTimeout(300);
  r.floatHide = await id(page);
  await page.screenshot({ path: `${out}/a-float-hide-${w}x${h}.png` });
  await page.keyboard.press('Escape'); await page.waitForTimeout(500);
  r.afterEscapePlaceholder = await page.evaluate(() => !!document.querySelector('[data-testid="arrangement-video-placeholder"]'));
  r.errors = errors;
  res[`${w}x${h}`] = r;
  await ctx.close();
}
await browser.close();
writeFileSync(`${out}/float-hide.json`, JSON.stringify(res, null, 1));
console.log(JSON.stringify(res, null, 1));
