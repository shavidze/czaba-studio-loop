import { chromium } from '/home/runner/czaba-project/store/node_modules/playwright/index.mjs';
import { writeFileSync } from 'node:fs';
const base = process.argv[2] ?? 'http://127.0.0.1:5173';
const out = process.argv[3] ?? 'remount-probe.json';
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await context.addInitScript(() => localStorage.setItem('czaba_analytics_consent', 'denied'));
const page = await context.newPage();
const status = () => page.evaluate(() => {
  const el = document.querySelector('[data-testid="arrangement-status"]');
  return { text: el?.textContent ?? null, key: el?.firstElementChild?.getAttribute('data-status-key') ?? null, html: el?.innerHTML.slice(0, 300) ?? null };
});
const playing = () => page.evaluate(() => document.querySelector('[data-playing]')?.getAttribute('data-playing') ?? null);
const steps = [];
await page.goto(`${base}/studio-lab`, { waitUntil: 'load', timeout: 120000 });
await page.waitForFunction(() => /ready/i.test(document.querySelector('[data-testid="arrangement-status"]')?.textContent ?? ''), null, { timeout: 120000 });
await page.waitForTimeout(1000);
steps.push({ step: 'ready', ...(await status()) });
await page.getByRole('button', { name: 'Add', exact: true }).first().click();
await page.locator('[data-clip-kind="audio"]').first().waitFor();
await page.waitForTimeout(1500);
steps.push({ step: 'after-add', ...(await status()) });
await page.evaluate(() => document.activeElement?.blur?.());
await page.keyboard.press('Space');
await page.waitForTimeout(1200);
steps.push({ step: 'playing', playing: await playing(), ...(await status()) });
await page.keyboard.press('Space');
await page.waitForTimeout(800);
steps.push({ step: 'stopped', playing: await playing(), ...(await status()) });
await page.setViewportSize({ width: 800, height: 900 });
await page.waitForTimeout(1500);
steps.push({ step: 'narrow', ...(await status()) });
await page.setViewportSize({ width: 1440, height: 900 });
await page.waitForTimeout(2000);
steps.push({ step: 'wide-again', playing: await playing(), ...(await status()) });
await page.screenshot({ path: out.replace(/\.json$/, '.png') });
writeFileSync(out, JSON.stringify({ base, steps }, null, 1));
console.log(JSON.stringify(steps, null, 1));
await browser.close();
