import { chromium } from '/home/runner/czaba-project/store/node_modules/playwright/index.mjs';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.addInitScript(() => localStorage.setItem('czaba_analytics_consent', 'denied'));
await page.goto('http://127.0.0.1:5173/studio-lab', { waitUntil: 'load', timeout: 120000 });
const add = page.getByRole('button', { name: 'Add', exact: true });
await page.waitForFunction(() => { const b=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()==='Add'); return b && !b.disabled; }, null, { timeout: 90000 });
await page.waitForTimeout(4000);
await add.click();
await page.locator('[data-clip-kind="audio"]').first().waitFor();
await page.waitForTimeout(1000);
const header = page.locator('[data-clip-kind="audio"]').first().getByTitle(/drag to move$/).first();
const box = await header.boundingBox();
await page.mouse.click(box.x + 40, box.y + box.height / 2);
await page.evaluate(() => document.activeElement instanceof HTMLElement && document.activeElement.blur());
await page.keyboard.press('Control+d');
await page.waitForTimeout(1500);
const info = await page.evaluate(() => {
  const s = document.querySelector('[data-testid="arrangement-timeline-scroller"]');
  const sb = s.getBoundingClientRect();
  const hw = document.querySelector('[data-testid="arrangement-track-header"]').getBoundingClientRect().width;
  const clips = [...document.querySelectorAll('[data-clip-kind="audio"]')].map((c) => ({ start: c.dataset.clipStart, left: c.getBoundingClientRect().left, right: c.getBoundingClientRect().right }));
  const detail = document.querySelector('[data-testid="arrangement-detail-start"]');
  return { scroller: [sb.left, sb.right, s.scrollLeft, s.clientWidth, s.scrollWidth], hw, clips, detail: detail?.value, counts: [...document.querySelectorAll('[data-track-id][data-clip-count]')].map((l) => l.getAttribute('data-clip-count')) };
});
console.log(JSON.stringify(info));
const follow = () => page.evaluate(() => { const b=[...document.querySelectorAll('button')].find(x=>/^Follow/.test(x.title)); return b ? b.title.slice(0,20) : null; });
const again = await header.boundingBox();
await page.keyboard.down('Control'); await page.mouse.click(again.x + 40, again.y + again.height / 2); await page.keyboard.up('Control');
await page.waitForTimeout(500);
await page.evaluate(() => document.activeElement instanceof HTMLElement && document.activeElement.blur());
await page.keyboard.press('Space');
await page.waitForTimeout(800);
await page.keyboard.press('Home');
await page.waitForTimeout(500);
console.log('playing, before scroll', await follow());
await page.evaluate(() => { document.querySelector('[data-testid="arrangement-timeline-scroller"]').scrollLeft = 4054; });
await page.waitForTimeout(400);
console.log('after scroll out', await follow());
await page.evaluate(() => { document.querySelector('[data-testid="arrangement-timeline-scroller"]').scrollLeft = 0; });
await page.waitForTimeout(400);
console.log('after scroll back', await follow());
await page.keyboard.press('Home');
await page.waitForTimeout(400);
console.log('after Home', await follow());
await browser.close();
