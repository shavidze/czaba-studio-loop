import { createRequire } from 'node:module';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const out = process.argv[2]; const BASE = 'http://127.0.0.1:5173';
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => { try { localStorage.setItem('czaba_lead_magnet_dismissed', '1'); sessionStorage.setItem('czaba_entrance_seen', '1'); } catch {} });
const page = await ctx.newPage(); const errs = []; page.on('pageerror', e => errs.push(String(e)));
await page.route(/\/products\/harbour-lights\?.*_data=/, async route => { const r = await route.fetch(); const j = await r.json(); const p = j.product; p.standardPrice = 0; p.premiumPrice = 0; p.minPrice = 0; p.variants = (p.variants || []).map(v => ({ ...v, price: 0 })); await route.fulfill({ response: r, json: j }); });
await page.goto(BASE + '/store', { waitUntil: 'load' }); await page.waitForTimeout(4000);
await page.screenshot({ path: `${out}/c13-1-store.png` });
const link = page.locator('a[href="/products/harbour-lights"]').first();
console.log('store card link', await link.count());
await link.click(); await page.waitForTimeout(3500);
console.log('url', page.url());
await page.screenshot({ path: `${out}/c13-2-product.png` });
const btn = page.getByRole('button', { name: 'Get it free', exact: true });
console.log('get it free', await btn.count());
await btn.click(); await page.waitForTimeout(1200);
console.log('modal email', await page.locator('input[type=email]').count(), 'toast', await page.getByText('Sign in to get it free.').count(), 'errs', errs.length);
await page.screenshot({ path: `${out}/c13-3-modal.png` });
await b.close();
