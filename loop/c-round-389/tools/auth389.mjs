import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const out = '/home/runner/czaba-project/tmp/studio-real-loop/c-round-389';
const res = {};
const browser = await chromium.launch();
for (const [w, h] of [[1440, 900], [1280, 720]]) {
  const k = `${w}x${h}`; const r = (res[k] = {});
  const ctx = await browser.newContext({ viewport: { width: w, height: h } });
  const page = await ctx.newPage();
  const errs = []; page.on('pageerror', e => errs.push(String(e).slice(0,150)));
  // G385-AUTH
  await page.goto('http://127.0.0.1:5173/studio-lab', { waitUntil: 'networkidle', timeout: 180000 });
  await page.waitForSelector('[data-testid="arrangement-timeline-scroller"]', { timeout: 120000 });
  r.authUser = await page.evaluate(() => localStorage.getItem('auth_user'));
  r.labOpen = true;
  await page.goto('http://127.0.0.1:5173/studio/middle-east', { waitUntil: 'networkidle', timeout: 180000 }).catch(e => r.studioGotoErr = String(e).slice(0,100));
  await page.waitForTimeout(3000);
  r.studioUrl = page.url();
  r.signInRequired = await page.getByText('Sign in required').first().isVisible().catch(() => false);
  r.audioSrc = await page.locator('audio[src]').count();
  r.timelinePresent = await page.locator('[data-testid="arrangement-timeline-scroller"]').count();
  await page.screenshot({ path: `${out}/screens/auth-studio-${k}.png` });
  const resp = await ctx.request.get('http://127.0.0.1:5173/api/studio-token?product=middle-east&file=stem.mp3');
  r.tokenStatus = resp.status(); r.tokenBody = (await resp.text()).slice(0, 200);
  r.tokenHasToken = /token/i.test(r.tokenBody) && !/sign in/i.test(r.tokenBody);
  // STUDIO-SMOKE
  const s = (r.smoke = {});
  await page.goto('http://127.0.0.1:5173/studio-lab', { waitUntil: 'networkidle', timeout: 180000 });
  await page.waitForSelector('[data-testid="arrangement-timeline-scroller"]', { timeout: 120000 });
  await page.getByText('Demo collection ready').first().waitFor({ timeout: 120000 }).catch(() => s.readyTimeout = true);
  await page.waitForTimeout(1200);
  await page.getByTestId('arrangement-library-list').getByRole('option', { name: /Middle East/ }).first().click();
  await page.waitForTimeout(250);
  s.clipsBefore = await page.locator('[data-clip-id]').count();
  await page.keyboard.press('Enter'); await page.waitForTimeout(1200);
  s.clipsAfter = await page.locator('[data-clip-id]').count();
  await page.screenshot({ path: `${out}/screens/smoke-clip-${k}.png` });
  const pos = async () => (await page.evaluate(() => document.body.innerText.match(/\d{1,2}:\d{2}(?:\.\d+)?/g) || [])).slice(0,4);
  const clockLoc = page.getByTestId('arrangement-clock').first();
  s.hasClockTestid = await clockLoc.count();
  const playBtn = page.getByRole('button', { name: /^Play/ }).first();
  s.playBtn = await playBtn.count();
  s.t0 = s.hasClockTestid ? await clockLoc.textContent() : await pos();
  await playBtn.click(); await page.waitForTimeout(1500);
  s.tPlaying = s.hasClockTestid ? await clockLoc.textContent() : await pos();
  await page.screenshot({ path: `${out}/screens/smoke-playing-${k}.png` });
  const stopBtn = page.getByRole('button', { name: /^(Stop|Pause)/ }).first();
  s.stopBtnName = await stopBtn.getAttribute('aria-label').catch(()=>null) || await stopBtn.textContent().catch(()=>null);
  await stopBtn.click(); await page.waitForTimeout(400);
  const a = s.hasClockTestid ? await clockLoc.textContent() : await pos(); await page.waitForTimeout(800);
  const b = s.hasClockTestid ? await clockLoc.textContent() : await pos();
  s.afterStop1 = a; s.afterStop2 = b; s.stopped = JSON.stringify(a) === JSON.stringify(b);
  s.status = (await page.getByTestId('arrangement-status').textContent().catch(() => ''))?.trim();
  const exp = page.getByRole('button', { name: /^Export/ }).first();
  s.exportBtn = await exp.count();
  await exp.click(); await page.waitForTimeout(800);
  s.dialog = await page.getByRole('dialog').count();
  await page.screenshot({ path: `${out}/screens/smoke-export-${k}.png` });
  s.dialogText = (await page.getByRole('dialog').first().innerText().catch(()=>'')).replace(/\s+/g,' ').slice(0,300);
  await page.keyboard.press('Escape'); await page.waitForTimeout(500);
  s.dialogAfterEsc = await page.getByRole('dialog').count();
  r.pageErrors = errs;
  await ctx.close();
  writeFileSync(`${out}/auth-smoke.json`, JSON.stringify(res, null, 1));
}
await browser.close();
