import { chromium } from '/home/runner/czaba-project/store/node_modules/playwright/index.mjs';
import { writeFileSync } from 'node:fs';
const base = 'http://127.0.0.1:5173';
const out = process.argv[2];
const [w, h] = (process.argv[3] ?? '1440x900').split('x').map(Number);
const hook = () => {
  const counts = new Map(); const seen = new WeakMap();
  const nameOf = (t) => { if (typeof t === 'function') return t.displayName || t.name || null; if (t && typeof t === 'object') { if (t.displayName) return t.displayName; if (t.render?.name) return t.render.name; } return null; };
  const walk = (root) => { const st = [root]; while (st.length) { const f = st.pop(); if (!f) continue; const n = nameOf(f.type); if (n) { const p = seen.get(f) ?? (f.alternate ? seen.get(f.alternate) : undefined); if (!p || p.p !== f.memoizedProps || p.s !== f.memoizedState) counts.set(n, (counts.get(n) ?? 0) + 1); seen.set(f, { p: f.memoizedProps, s: f.memoizedState }); if (f.alternate) seen.delete(f.alternate); } if (f.sibling) st.push(f.sibling); if (f.child) st.push(f.child); } };
  Object.defineProperty(window, '__REACT_DEVTOOLS_GLOBAL_HOOK__', { configurable: true, value: { isDisabled: false, supportsFiber: true, renderers: new Map(), inject: () => 1, checkDCE: () => undefined, onCommitFiberRoot: (_i, r) => walk(r.current), onCommitFiberUnmount: () => undefined, onPostCommitFiberRoot: () => undefined } });
  window.__renderCounts = counts;
};
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const ctx = await browser.newContext({ viewport: { width: w, height: h } });
await ctx.addInitScript(hook);
await ctx.addInitScript(() => localStorage.setItem('czaba_analytics_consent', 'denied'));
const page = await ctx.newPage();
const res = { viewport: `${w}x${h}`, pageErrors: [] };
page.on('pageerror', (e) => res.pageErrors.push(String(e)));
await page.goto(`${base}/studio-lab`, { waitUntil: 'load', timeout: 120000 });
await page.waitForFunction(() => /ready/i.test(document.querySelector('[data-testid="arrangement-status"]')?.textContent ?? ''), null, { timeout: 120000 });
await page.waitForTimeout(1000);
await page.getByTestId('arrangement-video-input').setInputFiles('/home/runner/czaba-project/store/public/videos/hero/1.mp4');
await page.locator('[data-clip-kind="video"]').first().waitFor(); await page.waitForTimeout(1500);
await page.evaluate(() => document.activeElement?.blur?.());
const cnt = () => page.evaluate(() => Object.fromEntries(['ArrangementVideoDock', 'ArrangementVideoDockViewInner', 'ArrangementVideoCaption'].map((n) => [n, window.__renderCounts.get(n) ?? 0])));
const dockAttrs = () => page.evaluate(() => { const d = document.querySelector('[data-testid="arrangement-video-dock"]'); return d ? Object.fromEntries([...d.attributes].filter((a) => a.name.startsWith('data-video')).map((a) => [a.name, a.value])) : null; });
const cap = () => page.evaluate(() => document.querySelector('[data-testid="arrangement-video-caption"]')?.textContent ?? null);
res.captionStopped = await cap();
await page.keyboard.press('Home'); await page.waitForTimeout(400);
await page.keyboard.press('Space'); await page.waitForTimeout(1500);
res.captionPlaying = await cap();
await page.keyboard.press('Space'); await page.waitForTimeout(500);
res.dockAttrsAfterPlay = await dockAttrs();
// positive control: expand
await page.evaluate(() => window.__renderCounts.clear());
res.countsBeforeExpand = await cnt();
const exp = page.getByTestId('arrangement-video-expand');
res.expandCount = await exp.count();
await exp.first().click(); await page.waitForTimeout(800);
res.countsAfterExpand = await cnt();
await page.screenshot({ path: out.replace(/\.json$/, '.png') });
writeFileSync(out, JSON.stringify(res, null, 1));
await browser.close();
