import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire('/home/runner/czaba-project/store/package.json');
const { chromium } = require('@playwright/test');
const OUT = '/home/runner/czaba-project/tmp/studio-real-loop/c-round-465';
const br = await chromium.launch({args:['--autoplay-policy=no-user-gesture-required']});
const res={};
for (const [w,h] of [[1440,900],[1280,720]]) {
  const r={}; res[w]=r;
  const ctx = await br.newContext({viewport:{width:w,height:h}});
  const p = await ctx.newPage();
  await p.addInitScript(()=>{ window.__ac=[]; const O=window.AudioContext; window.AudioContext=class extends O{constructor(...a){super(...a);window.__ac.push(this);}}; });
  await p.goto('http://127.0.0.1:5173/studio-lab',{waitUntil:'networkidle',timeout:120000}).catch(()=>{});
  await p.getByText('Demo collection ready').first().waitFor({timeout:60000});
  const clipsBefore = await p.locator('[data-testid*="clip"]').count();
  const opt = p.getByRole('option').filter({hasText:'Full mix'}).first();
  await opt.focus(); await p.keyboard.press('Enter'); await p.waitForTimeout(1500);
  r.clipsBefore=clipsBefore; r.clipsAfter=await p.locator('[data-testid*="clip"]').count();
  r.status = await p.locator('[role=status]').allInnerTexts();
  await p.screenshot({path:`${OUT}/smoke-added-${w}.png`});
  const clock = async()=> (await p.evaluate(()=>{const e=[...document.querySelectorAll('*')].find(x=>x.children.length===0&&/^\d\d:\d\d\.\d{3}$/.test(x.textContent.trim()));return e?e.textContent.trim():null;}));
  r.clock0 = await clock();
  await p.getByRole('button',{name:'Play',exact:true}).click();
  await p.waitForTimeout(1500);
  r.clockPlaying = await clock();
  r.ac = await p.evaluate(()=>window.__ac.map(a=>({state:a.state,t:a.currentTime})));
  await p.screenshot({path:`${OUT}/smoke-playing-${w}.png`});
  await p.getByRole('button',{name:'Stop',exact:true}).click();
  await p.waitForTimeout(500);
  const c1=await clock(); await p.waitForTimeout(800); const c2=await clock();
  r.afterStop=[c1,c2];
  await p.getByRole('button',{name:'Export',exact:true}).first().click();
  await p.waitForTimeout(800);
  r.dialog = await p.getByRole('dialog').count();
  r.dialogText=(await p.getByRole('dialog').first().innerText().catch(()=>'')).slice(0,300);
  await p.screenshot({path:`${OUT}/smoke-export-${w}.png`});
  await p.keyboard.press('Escape'); await p.waitForTimeout(500);
  r.dialogAfterEsc = await p.getByRole('dialog').count();
  await ctx.close();
}
fs.writeFileSync(`${OUT}/data/smoke.json`,JSON.stringify(res,null,1)); console.log(JSON.stringify(res,null,1));
await br.close();
