const { chromium } = require('/home/runner/czaba-project/store/node_modules/@playwright/test');
(async () => {
  const b = await chromium.launch(); const page = await b.newPage({ viewport: { width: 1440, height: 900 } });
  await page.goto('http://127.0.0.1:5173/studio-lab', { waitUntil: 'load' });
  await page.waitForSelector('[data-track-id="stems"]', { state: 'attached' }); await page.waitForTimeout(1500);
  const lane = (n) => page.getByRole('button', { name: new RegExp(`^${n} — აქტიური ხაზის არჩევა`) });
  const gname = (n) => page.getByRole('button', { name: new RegExp(`^${n} — ჯგუფი`) });
  const undo = () => page.locator('button[title^="Undo"]').first().getAttribute('title');
  const active = () => page.evaluate(() => document.activeElement?.getAttribute('aria-label') ?? document.activeElement?.tagName);
  const lanes = () => page.$$eval('[data-track-id]', (e) => e.map((x) => x.dataset.trackId));
  const out = {};
  await lane('სტემები').click(); await lane('SFX').click({ modifiers: ['Shift'] }); await page.keyboard.press('Control+g');
  out.afterGroup = await undo();
  const stemsFader = page.getByRole('slider', { name: /^Volume — სტემები/ });
  await stemsFader.focus();
  await page.keyboard.press('u');
  out.case1 = { lanes: await lanes(), undo: await undo(), focus: await active(), status: await page.getByTestId('arrangement-status').textContent() };
  await page.keyboard.press('u');
  await page.getByRole('slider', { name: /^Volume — სტემები/ }).focus();
  await page.keyboard.down('ArrowDown');
  await page.keyboard.press('u');
  await page.keyboard.up('ArrowDown');
  out.case2 = { lanes: await lanes(), undo: await undo(), focus: await active() };
  await page.locator('button[title^="Undo"]').first().click();
  out.case2AfterUndo = await undo();
  await page.locator('button[title^="Redo"]').first().click();
  await page.keyboard.press('u');
  await lane('მუსიკა').click(); await gname('ჯგუფი 1').click({ modifiers: ['Shift'] }); await page.keyboard.press('Control+g');
  const g1Fader = page.locator('[data-group-id]').filter({ has: gname('ჯგუფი 1') }).getByTestId('arrangement-group-volume');
  await g1Fader.focus();
  await page.keyboard.down('ArrowDown');
  await page.getByRole('button', { name: 'ჯგუფის დაკეცვა / გახსნა — ჯგუფი 2' }).click();
  await page.keyboard.up('ArrowDown');
  out.case3 = { lanes: await lanes(), undo: await undo(), focus: await active(), groups: await page.$$eval('[data-group-id]', (e) => e.map((x) => x.textContent.replace('▣', '').trim())) };
  console.log(JSON.stringify(out, null, 1));
  await b.close();
})();
