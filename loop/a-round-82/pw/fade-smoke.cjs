const { chromium } = require('/home/runner/czaba-project/store/node_modules/@playwright/test');
const out = '/home/runner/czaba-project/tmp/studio-real-loop/a-round-82/pw/';
(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await context.newPage();
  const errors = [];
  page.on('console', (m) => { if (m.type() === 'error' && !/cart|ERR_CONNECTION|ERR_TUNNEL|Failed to load resource/.test(m.text())) errors.push(m.text().slice(0, 200)); });
  await page.goto('http://127.0.0.1:5173/studio-lab', { waitUntil: 'networkidle' });
  const option = page.locator('[role="option"][data-source-id]').first();
  await option.waitFor();
  const sourceId = await option.getAttribute('data-source-id');
  await page.waitForTimeout(2500);
  await option.dblclick();
  await page.waitForTimeout(1500);
  const clip = page.locator('[data-clip-kind="audio"]').first();
  await clip.waitFor({ timeout: 15000 });
  const box = await clip.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  const handle = clip.locator('[data-testid="arrangement-clip-fade-in-handle"]');
  const hb = await handle.boundingBox();
  const opacity = await handle.evaluate((el) => getComputedStyle(el).opacity);
  const topEl = await page.evaluate(([x, y]) => document.elementFromPoint(x, y)?.getAttribute('data-testid'), [hb.x + 5, hb.y + 5]);
  await page.screenshot({ path: out + 'a-r82-hover-1440.png' });
  await page.mouse.move(hb.x + 5, hb.y + 5);
  await page.mouse.down();
  await page.mouse.move(hb.x + 45, hb.y + 5, { steps: 8 });
  await page.mouse.up();
  const fadeIn = await clip.getAttribute('data-fade-in');
  const pxps = await page.getByTestId('arrangement-zoom-readout').textContent();
  const status = await page.getByTestId('arrangement-status').textContent();
  await page.screenshot({ path: out + 'a-r82-fadein-1440.png' });
  console.log(JSON.stringify({ sourceId, clipBox: box, handleBox: hb, opacityOnHover: opacity, topEl, fadeIn, pxps, status, errors }));
  await context.storageState({ path: '/home/runner/czaba-project/tmp/studio-real-loop/a-browse.json' });
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
