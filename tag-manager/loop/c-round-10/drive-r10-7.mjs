import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { mkdtempSync, mkdirSync, copyFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
const REPO = '/home/runner/czaba-project/czaba-tag-manager';
const OUT = '/home/runner/czaba-project/tmp/tag-manager-loop/c-round-10';
const req = createRequire(REPO + '/package.json');
const { _electron } = req('playwright');
const mm = await import(pathToFileURL(req.resolve('music-metadata')).href);
const work = mkdtempSync(join(tmpdir(), 'c-r10-7-'));
const dir = join(work, 'wavs'); mkdirSync(dir); const cfg = join(work, 'xdg'); mkdirSync(cfg);
const F = join(dir, 'sample.wav'); copyFileSync(REPO + '/tests/fixtures/sample.wav', F);
const ffprobe = (p) => JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format_tags', '-of', 'json', p]).toString()).format?.tags ?? {};
const mmNative = async (p) => { const m = await mm.parseFile(p); const o = {}; for (const [k, v] of Object.entries(m.native)) o[k] = v.map((t) => [t.id, t.value]); return o; };
const r = { work, before: { ffprobe: ffprobe(F), mm: await mmNative(F) } };
const app = await _electron.launch({ args: ['--no-sandbox', join(REPO, 'out/main/index.js')], env: { ...process.env, XDG_CONFIG_HOME: cfg } });
const page = await app.firstWindow();
await page.setViewportSize({ width: 1400, height: 900 });
await page.waitForLoadState('domcontentloaded');
await app.evaluate(({ dialog }, d) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [d] }); }, dir);
await page.waitForTimeout(800);
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const fieldIn = (label) => page.locator('div.space-y-1', { has: page.locator('label', { hasText: new RegExp(`^${esc(label)}$`) }) }).locator('input').first();
const cell = () => page.getByText('sample.wav', { exact: true }).first();
const tagged = async () => (await cell().locator('xpath=../..').getByText('Tagged', { exact: true }).count()) > 0;
try {
  await page.getByText('Open Folder', { exact: true }).click();
  await cell().waitFor({ timeout: 15000 }); await page.waitForTimeout(1000);
  r.taggedOnOpen = await tagged();
  await page.screenshot({ path: join(OUT, 'r10-7-1-opened.png') });
  await cell().click(); await page.waitForTimeout(800);
  await fieldIn('Category (UCS)').fill('DOORWood');
  await page.screenshot({ path: join(OUT, 'r10-7-2-before-save.png') });
  await page.getByRole('button', { name: /Save Tags/ }).click();
  const t = page.getByText(/Tags saved|failed|Failed|Error/).first(); await t.waitFor({ timeout: 10000 });
  r.toast = await t.textContent();
  await page.screenshot({ path: join(OUT, 'r10-7-3-toast.png') });
  await page.waitForTimeout(1500);
  await page.getByText('Rescan', { exact: true }).click(); await page.waitForTimeout(2000); await cell().waitFor();
  r.taggedAfterRescan = await tagged();
  await page.screenshot({ path: join(OUT, 'r10-7-4-after-rescan.png') });
} catch (e) { r.error = String(e); await page.screenshot({ path: join(OUT, 'r10-7-error.png') }); }
await app.close();
r.after = { ffprobe: ffprobe(F), mm: await mmNative(F) };
writeFileSync(join(OUT, 'r10-7-result.json'), JSON.stringify(r, null, 2));
console.log(JSON.stringify(r, null, 1));
