const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const block = (label) => page.locator('div.space-y-1', { has: page.locator('label', { hasText: new RegExp(`^${esc(label)}$`) }) });
const fieldIn = (label) => block(label).locator('input, textarea').first();
const nameCell = (n) => page.locator('span.truncate.text-foreground', { hasText: new RegExp(`^${esc(n)}$`) }).first();
let shotN = 0;
const shot = async (name) => page.screenshot({ path: join(OUT, `${TAG}-${String(shotN++).padStart(2, '0')}-${name}.png`) });
const waitText = async (re, ms = 15000) => { const end = Date.now() + ms; while (Date.now() < end) { const r = (await page.locator('body').innerText()).match(re); if (r) return r[0]; await page.waitForTimeout(50); } return null; };
const ipcLog = () => app.evaluate(() => globalThis.__r38log);
const openFolder = async (dir) => { await setDialog(dir); await page.getByRole('button', { name: /Open Folder/ }).first().click(); };
const focusInfo = () => page.evaluate(() => {
  const a = document.activeElement;
  return { tag: a?.tagName ?? null, text: (a?.textContent ?? '').trim().slice(0, 60), ariaDisabled: a?.getAttribute('aria-disabled') ?? null, ariaBusy: a?.getAttribute('aria-busy') ?? null, disabledAttr: a?.hasAttribute('disabled') ?? null };
});
const btnState = (re) => page.evaluate((src) => {
  const re = new RegExp(src);
  const b = Array.from(document.querySelectorAll('button')).find((x) => re.test((x.textContent ?? '').trim()));
  if (!b) return null;
  let op = 1; for (let e = b; e; e = e.parentElement) op *= Number(getComputedStyle(e).opacity);
  const cs = getComputedStyle(b);
  return { text: (b.textContent ?? '').trim(), disabledAttr: b.hasAttribute('disabled'), ariaDisabled: b.getAttribute('aria-disabled'), ariaBusy: b.getAttribute('aria-busy'), ownOpacity: cs.opacity, effOpacity: Math.round(op * 1000) / 1000, cursor: cs.cursor, bg: cs.backgroundColor, color: cs.color, tabIndex: b.tabIndex };
}, re.source);
const arrowOpacities = () => page.evaluate(() => {
  const eff = (el) => { let op = 1; for (let e = el; e; e = e.parentElement) op *= Number(getComputedStyle(e).opacity); return Math.round(op * 1000) / 1000; };
  const ups = Array.from(document.querySelectorAll('fieldset button')).filter((b) => b.querySelector('svg.lucide-arrow-up'));
  const downs = Array.from(document.querySelectorAll('fieldset button')).filter((b) => b.querySelector('svg.lucide-arrow-down'));
  const fs = document.querySelector('fieldset');
  return { count: ups.length, fieldsetDisabled: fs?.disabled ?? null, fieldsetOpacity: fs ? getComputedStyle(fs).opacity : null, firstUp: eff(ups[0]), firstUpOwn: getComputedStyle(ups[0]).opacity, middleUp: eff(ups[1]), middleUpOwn: getComputedStyle(ups[1]).opacity, lastDown: eff(downs[downs.length - 1]), middleDown: eff(downs[1]), firstUpClass: ups[0].className, middleUpClass: ups[1].className };
});
