import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { mkdtempSync, mkdirSync, copyFileSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
const REPO = '/home/runner/czaba-project/czaba-tag-manager';
const APPROOT = process.argv[2]; const LABEL = process.argv[3]; const SCEN = process.argv[4];
const OUT = '/home/runner/czaba-project/tmp/tag-manager-loop/c-round-29';
const TAG = `r29-5-${LABEL}-${SCEN}`;
const req = createRequire(REPO + '/package.json');
const { _electron } = req('playwright');
const mm = await import(pathToFileURL(req.resolve('music-metadata')).href);
const work = mkdtempSync(join(tmpdir(), `c-r29-${LABEL}-${SCEN}-`));
const dir = join(work, 'wavs'); mkdirSync(dir);
const other = join(work, 'other'); mkdirSync(other);
const cfg = join(work, 'xdg'); mkdirSync(cfg);
const armFile = join(work, 'ARM');
for (const n of ['a.wav', 'b.wav']) copyFileSync(REPO + '/tests/fixtures/sample.wav', join(dir, n));
for (const n of ['c.wav', 'd.wav']) copyFileSync(REPO + '/tests/fixtures/sample.wav', join(other, n));
const result = { label: LABEL, scenario: SCEN, appRoot: APPROOT, workDir: work, phases: {}, checks: {} };
const ok = (k, v, detail) => { result.checks[k] = { pass: !!v, detail }; };
const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');
const shas = () => ({ a: sha(join(dir, 'a.wav')), b: sha(join(dir, 'b.wav')) });
const ffprobe = (p) => { try { return JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format_tags', '-of', 'json', p]).toString()).format?.tags ?? {}; } catch (e) { return { error: String(e).slice(0, 200) }; } };
async function mmRead(p) { try { const m = await mm.parseFile(p); const native = {}; for (const [k, v] of Object.entries(m.native)) for (const t of v) native[`${k}:${t.id}`] = t.value; return { title: m.common.title, artist: m.common.artist, native }; } catch (e) { return { error: String(e) }; } }
const readA = async () => { const p = join(dir, 'a.wav'); const f = ffprobe(p); const m = await mmRead(p); return { ffprobe: f, mmNative: m.native, ffICAT: f.ICAT ?? f.icat, mmICAT: m.native?.['exif:ICAT'], ffArtist: f.artist, mmArtist: m.artist }; };
result.initialA = await readA();
const app = await _electron.launch({ args: ['--no-sandbox', '-r', join(OUT, 'harness.cjs'), join(APPROOT, 'out/main/index.js')], env: { ...process.env, XDG_CONFIG_HOME: cfg, R29_ARM_FILE: armFile } });
const page = await app.firstWindow();
await page.setViewportSize({ width: 1400, height: 900 });
await page.waitForLoadState('domcontentloaded');
const setDialog = (d) => app.evaluate(({ dialog }, d) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [d] }); }, d);
await setDialog(dir);
await page.waitForTimeout(800);
let phase = 'scan';
const pageErrors = []; const toastsSeen = [];
page.on('pageerror', (e) => pageErrors.push(`${phase}: ${String(e)}`));
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const block = (label) => page.locator('div.space-y-1', { has: page.locator('label', { hasText: new RegExp(`^${esc(label)}$`) }) });
const fieldIn = (label) => block(label).locator('input, textarea').first();
const val = async (label) => ((await block(label).count()) ? await fieldIn(label).inputValue() : '<no field>');
const nameCell = (n) => page.locator('span.truncate.text-foreground', { hasText: new RegExp(`^${esc(n)}$`) }).first();
const rowOf = (n) => nameCell(n).locator('xpath=../..');
const rowInfo = async (n) => { if (!(await nameCell(n).count())) return { listed: false }; const r = rowOf(n); return { listed: true, tagged: (await r.locator('text=Tagged').count()) > 0, text: (await r.innerText()).replace(/\s+/g, ' ') }; };
let shotN = 0;
const shot = async (name) => page.screenshot({ path: join(OUT, `${TAG}-${String(shotN++).padStart(2, '0')}-${name}.png`) });
const TOAST_RE = /(Unsaved changes[^\n]*|Tags saved[^\n]*|\d+ saved, \d+ failed[^\n]*|Failed[^\n]*|Rescan failed[^\n]*|R29 harness[^\n]*)/g;
const pollToasts = async () => { const t = await page.locator('body').innerText(); for (const m of t.match(TOAST_RE) ?? []) { const k = `${phase}: ${m}`; if (!toastsSeen.includes(k)) toastsSeen.push(k); } };
const waitToast = async (re, ms = 15000) => { const end = Date.now() + ms; while (Date.now() < end) { await pollToasts(); const t = await page.locator('body').innerText(); const m = t.match(re); if (m) return { text: m[0], at: Date.now() }; await page.waitForTimeout(50); } return null; };
const form = async () => ({ title: await val('Title'), category: await val('Category (UCS)'), artists: await val('Artists') });
const ipcLog = () => app.evaluate(() => globalThis.__r29log);
const waitLog = async (pred, ms = 10000) => { const end = Date.now() + ms; while (Date.now() < end) { const l = await ipcLog(); const e = l.find(pred); if (e) return e; await page.waitForTimeout(50); } return null; };
try {
  await page.getByText('Open Folder', { exact: true }).first().click();
  await nameCell('a.wav').waitFor({ timeout: 30000 }); await page.waitForTimeout(1200);
  result.phases.scan = { a: await rowInfo('a.wav'), b: await rowInfo('b.wav') };
  await shot('scan');
  phase = 'setup';
  await nameCell('a.wav').click(); await page.waitForTimeout(600);
  result.phases.setup = { before: await form() };
  await fieldIn('Category (UCS)').fill('R29Cat');
  await page.getByRole('button', { name: /Save Tags/ }).click();
  result.phases.setup.toast = await waitToast(/Tags saved/);
  await page.waitForTimeout(3600);
  result.phases.setup.after = await form();
  result.phases.setup.rows = { a: await rowInfo('a.wav'), b: await rowInfo('b.wav') };
  await shot('setup-saved');
  result.shaAfterSetup = shas();
  result.readersAfterSetup = await readA();
  phase = 'action';
  writeFileSync(armFile, '1');
  const nLogBefore = (await ipcLog()).length;
  if (SCEN === 'C') await setDialog(other);
  const btn = SCEN === 'A' ? 'Rescan' : 'Open Folder';
  await page.getByRole('button', { name: new RegExp(btn) }).first().click();
  const thrown = await waitLog((e) => e.phase === 'throw', 10000);
  const t = await waitToast(/Failed to read \d+ files|Rescan failed|Failed to open folder|Failed to scan folder|R29 harness[^\n]*/, 2500);
  await page.waitForTimeout(150);
  await pollToasts();
  await shot(`action-${btn.replace(' ', '')}-list-toast`);
  rmSync(armFile, { force: true });
  result.phases.action = { button: btn, harnessThrew: !!thrown, thrownPaths: thrown?.paths, toast: t, ipcSinceArm: (await ipcLog()).slice(nLogBefore).map((e) => ({ channel: e.channel, phase: e.phase, armed: e.armed, paths: e.paths })) };
  if (SCEN === 'C') {
    result.phases.action.rows = { c: await rowInfo('c.wav'), d: await rowInfo('d.wav'), a: await rowInfo('a.wav') };
    phase = 'click-c';
    await nameCell('c.wav').click(); await page.waitForTimeout(800);
    result.phases.clickC = { form: await form() };
    await shot('click-c-form');
  } else {
    result.phases.action.rows = { a: await rowInfo('a.wav'), b: await rowInfo('b.wav') };
    phase = 'click-a';
    await nameCell('a.wav').click(); await page.waitForTimeout(800);
    result.phases.clickA = { form: await form(), rows: { a: await rowInfo('a.wav') } };
    await fieldIn('Category (UCS)').scrollIntoViewIfNeeded().catch(() => {});
    await shot('click-a-form');
  }
} catch (e) {
  result.error = String(e?.stack ?? e);
  await shot('error').catch(() => {});
}
result.ipc = await ipcLog().catch(() => []);
await pollToasts();
await app.close().catch(() => {});
result.pageErrors = pageErrors; result.toastsSeen = toastsSeen;
result.shaFinal = shas();
result.readersFinal = await readA();
const R = result.readersFinal;
ok('setup Tags saved', !!result.phases.setup?.toast);
ok('harness threw on read-batch', !!result.phases.action?.harnessThrew, result.phases.action?.thrownPaths);
ok('toast Failed to read 2 files', result.phases.action?.toast?.text === 'Failed to read 2 files', result.phases.action?.toast);
if (SCEN === 'C') {
  const rows = result.phases.action?.rows ?? {};
  ok('C: c,d listed', rows.c?.listed && rows.d?.listed, rows);
  ok('C: c,d no Tagged badge', rows.c && !rows.c.tagged && rows.d && !rows.d.tagged, rows);
} else {
  ok('a.wav keeps Tagged badge after action', result.phases.action?.rows?.a?.tagged === true, result.phases.action?.rows);
  ok('form Category=R29Cat after click a', result.phases.clickA?.form?.category === 'R29Cat', result.phases.clickA?.form);
}
ok('sha unchanged by action', JSON.stringify(result.shaAfterSetup) === JSON.stringify(result.shaFinal), { afterSetup: result.shaAfterSetup, final: result.shaFinal });
ok('readers ICAT=R29Cat (ffprobe + music-metadata)', R.ffICAT === 'R29Cat' && R.mmICAT === 'R29Cat', { ffICAT: R.ffICAT, mmICAT: R.mmICAT });
ok('pageErrors-empty', pageErrors.length === 0, pageErrors);
writeFileSync(join(OUT, `${TAG}.json`), JSON.stringify(result, null, 2));
console.log(LABEL, SCEN, JSON.stringify(Object.fromEntries(Object.entries(result.checks).map(([k, v]) => [k, v.pass])), null, 1));
console.log('toastsSeen', JSON.stringify(toastsSeen));
if (result.error) console.log('ERROR', result.error);
