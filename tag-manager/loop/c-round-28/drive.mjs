const saveRead = ipc.find((e) => e.channel === 'meta:read' && e.phase === 'reply' && writeEnd && e.at >= writeEnd.at);
result.timing = { lateStart: lateStart?.ms, lateListenerDone: lateDone?.ms, lateValues: lateDone?.values, writeEnd: writeEnd?.ms, saveReReadReply: saveRead?.ms, lateReply: lateReply?.ms };
ok('log: folder read started+read before write ended', lateStart && writeEnd && lateDone.at < writeEnd.at, result.timing);
ok('log: folder read replied after save meta:read', lateReply && saveRead && lateReply.at > saveRead.at, result.timing);
const s4 = result.phases.step4 ?? {}; const A = result.finalA;
ok('step4 form Category=R28Cat', s4.form?.category === 'R28Cat', s4.form);
ok('readers ICAT=R28Cat', A.ffICAT === 'R28Cat' && A.mmICAT === 'R28Cat', { ffICAT: A.ffICAT, mmICAT: A.mmICAT });
ok('readers title=R28T2', A.ffTitle === 'R28T2' && A.mmINAM === 'R28T2', { ffTitle: A.ffTitle, mmINAM: A.mmINAM, mmTitle: A.mmTitle });
ok('pageErrors-empty', pageErrors.length === 0, pageErrors);
writeFileSync(join(OUT, `${TAG}.json`), JSON.stringify(result, null, 2));
console.log(LABEL, SCEN, JSON.stringify(result.checks, null, 1));
if (result.error) console.log('ERROR', result.error);
