import { createRequire } from 'node:module';
import { mkdtempSync, mkdirSync, copyFileSync, writeFileSync, rmSync, readFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const REPO = '/home/runner/czaba-project/czaba-tag-manager';
const APPROOT = process.argv[2]; const LABEL = process.argv[3]; const SCEN = process.argv[4] ?? 'hover';
const OUT = process.env.C40_OUT ?? '/home/runner/czaba-project/tmp/tag-manager-loop/c-round-40';
const HARNESS = '/home/runner/czaba-project/tmp/tag-manager-loop/c-round-38/harness.cjs';
const SAMPLE = '/tmp/b40/sample.wav';
const req = createRequire(REPO + '/package.json');
const { _electron } = req('playwright');
const work = mkdtempSync(join(tmpdir(), `c-r40-${LABEL}-`));
const fa = join(work, 'fa'); mkdirSync(fa); const fb = join(work, 'fb'); mkdirSync(fb);
const cfg = join(work, 'xdg'); mkdirSync(cfg);
const SCAN_ARM = join(work, 'ARM_SCAN'); const WRITE_ARM = join(work, 'ARM_WRITE');
for (const n of ['a.wav', 'a2.wav']) copyFileSync(SAMPLE, join(fa, n));
copyFileSync(SAMPLE, join(fb, 'b.wav'));
const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');
const shaAll = () => Object.fromEntries([fa, fb].flatMap((d) => readdirSync(d).map((n) => [join(d, n), sha(join(d, n))])));
const result = { label: LABEL, scen: SCEN, appRoot: APPROOT, work, steps: [], extra: {} };
const app = await _electron.launch({ args: ['--no-sandbox', '-r', HARNESS, join(APPROOT, 'out/main/index.js')], env: { ...process.env, XDG_CONFIG_HOME: cfg, R38_SCAN_ARM: SCAN_ARM, R38_WRITE_ARM: WRITE_ARM, R38_SCAN_MS: '16000', R38_WRITE_MS: '5000' } });
const page = await app.firstWindow();
await page.setViewportSize({ width: 1400, height: 900 });
await page.waitForLoadState('domcontentloaded');
await page.waitForTimeout(800);
const pageErrors = []; page.on('pageerror', (e) => pageErrors.push(String(e)));
const setDialog = (d) => app.evaluate(({ dialog }, d) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [d] }); }, d);
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const block = (label) => page.locator('div.space-y-1', { has: page.locator('label', { hasText: new RegExp(`^${esc(label)}$`) }) });
const fieldIn = (label) => block(label).locator('input, textarea').first();
const nameCell = (n) => page.locator('span.truncate.text-foreground', { hasText: new RegExp(`^${esc(n)}$`) }).first();
const openFolder = async (dir) => { await setDialog(dir); await page.getByRole('button', { name: /Open Folder/ }).first().click(); };
const shot = (name) => page.screenshot({ path: join(OUT, `${LABEL}-${name}.png`) });
const styleOf = (loc) => loc.evaluate((b) => { const cs = getComputedStyle(b); let op = 1; for (let e = b; e; e = e.parentElement) op *= Number(getComputedStyle(e).opacity); return { text: (b.textContent ?? '').trim(), matchesHover: b.matches(':hover'), disabledProp: b.disabled, matchesDisabled: b.matches(':disabled'), ariaDisabled: b.getAttribute('aria-disabled'), ariaBusy: b.getAttribute('aria-busy'), bg: cs.backgroundColor, color: cs.color, border: cs.borderColor, cursor: cs.cursor, boxShadow: cs.boxShadow, focusVisible: b.matches(':focus-visible'), isActive: document.activeElement === b, effOpacity: Math.round(op * 1000) / 1000 }; });
const park = async () => { await page.mouse.move(2, 890); await page.waitForTimeout(400); };
const measure = async (name, loc) => {
  await park();
  const rest = await styleOf(loc);
  await loc.hover({ force: true });
  await page.waitForTimeout(400);
  const hover = await styleOf(loc);
  await shot(name);
  result.steps.push({ name, rest, hover, bgChanges: rest.bg !== hover.bg, colorChanges: rest.color !== hover.color, borderChanges: rest.border !== hover.border });
};
const ipcLog = () => app.evaluate(() => globalThis.__r38log);
const playBtn = page.locator('button').filter({ has: page.locator('svg.lucide-play, svg.lucide-pause') }).last();
try {
  result.media = await page.evaluate(() => ({ hoverHover: matchMedia('(hover: hover)').matches, anyHover: matchMedia('(any-hover: hover)').matches }));
  await openFolder(fa);
  await nameCell('a.wav').waitFor({ timeout: 30000 }); await page.waitForTimeout(800);
  if (SCEN === 'k2') {
    result.shaBefore = shaAll();
    await nameCell('a.wav').click(); await page.waitForTimeout(500);
    await fieldIn('Category (UCS)').fill('C40Keyb'); await page.waitForTimeout(300);
    const save = page.locator('button', { hasText: /^(Save Tags|Saving\.\.\.)$/ });
    writeFileSync(WRITE_ARM, '1');
    await save.focus();
    const t0 = Date.now();
    await page.keyboard.press('Enter'); await page.waitForTimeout(500);
    result.extra.during = await styleOf(save);
    await shot('k2-saving');
    await page.keyboard.press('Enter'); await page.waitForTimeout(300);
    result.extra.during2 = await styleOf(save);
    await page.getByText(/Tags saved/).first().waitFor({ timeout: 20000 });
    await page.waitForTimeout(800);
    result.extra.after = await styleOf(save);
    await shot('k2-after');
    rmSync(WRITE_ARM, { force: true });
    const log = await ipcLog();
    result.extra.writes = log.filter((e) => e.channel === 'meta:write' && e.phase === 'start' && e.at >= t0).length;
    result.extra.batchWrites = log.filter((e) => e.channel === 'meta:write-batch' && e.phase === 'start' && e.at >= t0).length;
    result.shaAfter = shaAll();
  } else {
    await measure('H11-player-disabled', playBtn);
    await nameCell('a.wav').click(); await page.waitForTimeout(500);
    const save = page.locator('button', { hasText: /^(Save Tags|Saving\.\.\.)$/ });
    await measure('H1-clean-save', save);
    await fieldIn('Category (UCS)').focus(); await page.keyboard.press('Shift+Tab'); await page.keyboard.press('Tab');
    await save.focus(); await page.waitForTimeout(300);
    result.extra.dev3FocusCleanSave = await styleOf(save);
    await save.screenshot({ path: join(OUT, `${LABEL}-DEV3-focus-ring-clean-save.png`) });
    await shot('DEV3-focus-ring-full');
    await page.locator('body').click({ position: { x: 700, y: 880 } }).catch(() => {});
    await fieldIn('Category (UCS)').fill('C40Hover'); await page.waitForTimeout(300);
    await measure('H0-dirty-save-control', save);
    writeFileSync(WRITE_ARM, '1');
    await save.click(); await page.waitForTimeout(300);
    await measure('H2-busy-save', save);
    rmSync(WRITE_ARM, { force: true });
    await page.waitForTimeout(6000);
    await page.locator('button[title="Customize Fields"]').click();
    await page.getByText('Active Fields').waitFor();
    const back = page.locator('button').filter({ has: page.locator('svg.lucide-arrow-left') }).first();
    await measure('DEV4-back-arrow', back);
    await page.locator('input[placeholder="Field name (e.g. Client)"]').fill('C40Client');
    await page.locator('fieldset button', { hasText: /Add Field/ }).click(); await page.waitForTimeout(300);
    await page.locator('fieldset button[title="Hide standard field"]').last().click(); await page.waitForTimeout(300);
    const middleUp = page.locator('fieldset button').filter({ has: page.locator('svg.lucide-arrow-up') }).nth(1);
    const edgeUp = page.locator('fieldset button').filter({ has: page.locator('svg.lucide-arrow-up') }).first();
    const done = page.locator('button', { hasText: /^(Done|Applying\.\.\.)$/ });
    const trash = page.locator('fieldset button').filter({ has: page.locator('svg[class*="lucide-trash"]') }).first();
    const chip = page.locator('fieldset button', { hasText: /^\+ / }).first();
    const xBtn = page.locator('fieldset button[title="Hide standard field"]').first();
    const addField = page.locator('fieldset button', { hasText: /Add Field/ });
    result.extra.chipCount = await page.locator('fieldset button', { hasText: /^\+ / }).count();
    result.extra.trashCount = await page.locator('fieldset button').filter({ has: page.locator('svg[class*="lucide-trash"]') }).count();
    await measure('H3-rest-middle-arrow-control', middleUp);
    await measure('EDGE-rest-edge-arrow', edgeUp);
    await measure('H3b-rest-done-control', done);
    await measure('H6b-rest-hide-standard-x-control', xBtn);
    await measure('H7b-rest-add-field-control', addField);
    await measure('H9-rest-trash-enabled', trash);
    await measure('H10-rest-chip-enabled', chip);
    writeFileSync(SCAN_ARM, '1');
    await openFolder(fb);
    await page.waitForTimeout(400);
    await done.click(); await page.waitForTimeout(300);
    await measure('H4-applying-done', done);
    await measure('H5-applying-middle-arrow', middleUp);
    await measure('H6-applying-hide-standard-x', xBtn);
    await measure('H7-applying-add-field', addField);
    await measure('H9-applying-trash', trash);
    await measure('H10-applying-chip', chip);
    await measure('H8-scanning-rescan', page.locator('button', { hasText: /^Rescan$/ }));
    rmSync(SCAN_ARM, { force: true });
    await page.waitForTimeout(14000);
    await nameCell('b.wav').waitFor({ timeout: 20000 });
    await nameCell('b.wav').dblclick(); await page.waitForTimeout(1200);
    await measure('H11-player-enabled', playBtn);
  }
} catch (e) { result.error = String(e?.stack ?? e); await shot('error').catch(() => {}); }
await app.close().catch(() => {});
result.pageErrors = pageErrors;
writeFileSync(join(OUT, `${LABEL}-${SCEN}.json`), JSON.stringify(result, null, 2));
const fmt = (s) => `${s.bg} ${s.color} ${s.border} op${s.effOpacity} ${s.cursor} dis=${s.disabledProp} aria=${s.ariaDisabled} busy=${s.ariaBusy}`;
for (const s of result.steps) console.log(`${s.name.padEnd(34)} ${s.bgChanges || s.colorChanges || s.borderChanges ? 'CHANGES' : 'same   '} | rest ${fmt(s.rest)} | hover ${fmt(s.hover)}`);
console.log(JSON.stringify({ error: result.error, pageErrors, extra: result.extra, media: result.media }, null, 1));
