import { createRequire } from 'node:module';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const req = createRequire('/home/runner/czaba-project/czaba-tag-manager/package.json');
const { _electron } = req('playwright');
const [APPROOT, LABEL] = process.argv.slice(2);
const OUT = '/home/runner/czaba-project/tmp/tag-manager-loop/c-round-40';
const cfg = mkdtempSync(join(tmpdir(), 'c40-of-')); mkdirSync(join(cfg, 'xdg'));
const app = await _electron.launch({ args: ['--no-sandbox', join(APPROOT, 'out/main/index.js')], env: { ...process.env, XDG_CONFIG_HOME: join(cfg, 'xdg') } });
const page = await app.firstWindow(); await page.setViewportSize({ width: 1400, height: 900 }); await page.waitForTimeout(1200);
const btn = page.getByRole('button', { name: /Open Folder/ }).first();
const st = () => btn.evaluate((b) => { const c = getComputedStyle(b); return { bg: c.backgroundColor, color: c.color, border: c.borderColor, cursor: c.cursor, opacity: c.opacity }; });
await page.mouse.move(2, 890); await page.waitForTimeout(400); const rest = await st();
await btn.hover(); await page.waitForTimeout(400); const hover = await st();
await page.screenshot({ path: join(OUT, `${LABEL}-OPENFOLDER-secondary-hover.png`) });
await app.close();
const r = { label: LABEL, rest, hover, changes: rest.bg !== hover.bg };
writeFileSync(join(OUT, `${LABEL}-openfolder.json`), JSON.stringify(r, null, 2)); console.log(JSON.stringify(r));
