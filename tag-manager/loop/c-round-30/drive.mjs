import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { mkdtempSync, mkdirSync, copyFileSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
const REPO = '/home/runner/czaba-project/czaba-tag-manager';
const APPROOT = process.argv[2]; const LABEL = process.argv[3]; const SCEN = process.argv[4];
const OUT = '/home/runner/czaba-project/tmp/tag-manager-loop/c-round-30';
const HARNESS = '/home/runner/czaba-project/tmp/tag-manager-loop/c-round-29/harness.cjs';
const TAG = `r30-5-${LABEL}-${SCEN}`;
const req = createRequire(REPO + '/package.json');
const { _electron } = req('playwright');
const mm = await import(pathToFileURL(req.resolve('music-metadata')).href);
const work = mkdtempSync(join(tmpdir(), `c-r30-${LABEL}-${SCEN}-`));
const m = join(work, 'm'); mkdirSync(m);
const empty = join(work, 'empty'); mkdirSync(empty); writeFileSync(join(empty, 'notes.txt'), 'no wav here');
const o = join(work, 'o'); mkdirSync(o);
const cfg = join(work, 'xdg'); mkdirSync(cfg);
const armFile = join(work, 'ARM');
for (const n of ['a.wav', 'b.wav']) copyFileSync(REPO + '/tests/fixtures/sample.wav', join(m, n));
for (const n of ['c.wav', 'd.wav']) copyFileSync(REPO + '/tests/fixtures/sample.wav', join(o, n));
const mid = SCEN === 'O' ? o : empty;
const result = { label: LABEL, scenario: SCEN, appRoot: APPROOT, workDir: work, phases: {}, checks: {} };
const ok = (k, v, detail) => { result.checks[k] = { pass: !!v, detail }; };
const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');
const shas = () => ({ a: sha(join(m, 'a.wav')), b: sha(join(m, 'b.wav')) });
const ffprobe = (p) => { try { return JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format_tags', '-of', 'json', p]).toString()).format?.tags ?? {}; } catch (e) { return { error: String(e).slice(0, 200) }; } };
async function mmRead(p) { try { const r = await mm.parseFile(p); const native = {}; for (const [k, v] of Object.entries(r.native)) for (const t of v) native[`${k}:${t.id}`] = t.value; return { title: r.common.title, artist: r.common.artist, native }; } catch (e) { return { error: String(e) }; } }
const readA = async () => { const p = join(m, 'a.wav'); const f = ffprobe(p); const r = await mmRead(p); return { ffprobe: f, mmNative: r.native, ffICAT: f.ICAT ?? f.icat, mmICAT: r.native?.['exif:ICAT'], ffArtist: f.artist, mmArtist: r.artist }; };
result.initialA = await readA();
const app = await _electron.launch({ args: ['--no-sandbox', '-r', HARNESS, join(APPROOT, 'out/main/index.js')], env: { ...process.env, XDG_CONFIG_HOME: cfg, R29_ARM_FILE: armFile } });
const page = await app.firstWindow();
await page.setViewportSize({ width: 1400, height: 900 });
await page.waitForLoadState('domcontentloaded');
const setDialog = (d) => app.evaluate(({ dialog }, d) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [d] }); }, d);
await setDialog(m);
await page.waitForTimeout(800);
let phase = 'scan';
const pageErrors = []; const toastsSeen = [];
page.on('pageerror', (e) => pageErrors.push(`${phase}: ${String(e)}`));
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const block = (label) => page.locator('div.space-y-1', { has: page.locator('label', { hasText: new RegExp(`^${esc(label)}$`) }) });
const fieldIn = (label) => block(label).locator('input, textarea').first();
const val = async (label) => ((await block(label).count()) ? await fieldIn(label).inputValue() : '<no field>');
const nameCell = (n) => page.locator('span.truncate.text-foreground', { hasText: new RegExp(`^${esc(n)}$`) }).first();
const rowOf = (n) => nameCell(n).locator('xpath=../..');
const rowInfo = async (n) => { if (!(await nameCell(n).count())) return { listed: false }; const r = rowOf(n); return { listed: true, tagged: (await r.locator('text=Tagged').count()) > 0, text: (await r.innerText()).replace(/\s+/g, ' ') }; };
const allRows = async () => (await page.locator('span.truncate.text-foreground').allInnerTexts()).filter((t) => /\.wav$/i.test(t));
let shotN = 0;
const shot = async (name) => page.screenshot({ path: join(OUT, `${TAG}-${String(shotN++).padStart(2, '0')}-${name}.png`) });
const TOAST_RE = /(Unsaved changes[^\n]*|Tags saved[^\n]*|\d+ saved, \d+ failed[^\n]*|Failed[^\n]*|Rescan failed[^\n]*|Folder is empty[^\n]*|R29 harness[^\n]*)/g;
const toastsNow = async () => (await page.locator('body').innerText()).match(TOAST_RE) ?? [];
const pollToasts = async () => { for (const t of await toastsNow()) { const k = `${phase}: ${t}`; if (!toastsSeen.includes(k)) toastsSeen.push(k); } };
const waitToast = async (re, ms = 15000) => { const end = Date.now() + ms; while (Date.now() < end) { await pollToasts(); const t = await page.locator('body').innerText(); const r = t.match(re); if (r) return { text: r[0], at: Date.now() }; await page.waitForTimeout(50); } return null; };
const waitNoToast = async (ms = 8000) => { const end = Date.now() + ms; while (Date.now() < end) { if ((await toastsNow()).length === 0) return true; await page.waitForTimeout(100); } return false; };
const watchToasts = async (ms) => { const seen = new Set(); const end = Date.now() + ms; while (Date.now() < end) { for (const t of await toastsNow()) seen.add(t); await pollToasts(); await page.waitForTimeout(50); } return [...seen]; };
const form = async () => ({ title: await val('Title'), category: await val('Category (UCS)'), artists: await val('Artists') });
const ipcLog = () => app.evaluate(() => globalThis.__r29log);
const waitLog = async (pred, from, ms = 10000) => { const end = Date.now() + ms; while (Date.now() < end) { const l = (await ipcLog()).slice(from); const e = l.find(pred); if (e) return e; await page.waitForTimeout(50); } return null; };
try {
  await page.getByText('Open Folder', { exact: true }).first().click();
  await nameCell('a.wav').waitFor({ timeout: 30000 }); await page.waitForTimeout(1200);
  result.phases.scan = { a: await rowInfo('a.wav'), b: await rowInfo('b.wav') };
  await shot('scan');
  phase = 'setup';
  await nameCell('a.wav').click(); await page.waitForTimeout(600);
  result.phases.setup = { before: await form() };
  await fieldIn('Category (UCS)').fill('R30Cat');
  await page.getByRole('button', { name: /Save Tags/ }).click();
  result.phases.setup.toast = await waitToast(/Tags saved/);
  await page.waitForTimeout(1500);
  result.phases.setup.after = await form();
  result.phases.setup.rows = { a: await rowInfo('a.wav'), b: await rowInfo('b.wav') };
  await shot('setup-saved');
  result.phases.setup.toastGone = await waitNoToast(10000);
  result.shaAfterSetup = shas();
  result.readersAfterSetup = await readA();
  phase = `open-${SCEN === 'O' ? 'o' : 'empty'}`;
  await setDialog(mid);
  await page.getByRole('button', { name: /Open Folder/ }).first().click();
  if (SCEN === 'O') await nameCell('c.wav').waitFor({ timeout: 15000 });
  const midToasts = await watchToasts(2000);
  result.phases.mid = { rows: await allRows(), toasts: midToasts };
  await shot(`${phase}-list`);
  phase = 'armed-open-m';
  writeFileSync(armFile, '1');
  const nLog = (await ipcLog()).length;
  await setDialog(m);
  await page.getByRole('button', { name: /Open Folder/ }).first().click();
  const thrown = await waitLog((e) => e.phase === 'throw', nLog, 10000);
  const t = await waitToast(/Failed to read \d+ files|Rescan failed|Failed to open folder|Failed to scan folder|R29 harness[^\n]*/, 3000);
  await page.waitForTimeout(150);
  result.phases.armed = { harnessThrew: !!thrown, thrownPaths: thrown?.paths, toast: t, rows: { a: await rowInfo('a.wav'), b: await rowInfo('b.wav') } };
  await shot('armed-open-m-list-toast');
  rmSync(armFile, { force: true });
  phase = 'click-a';
  await nameCell('a.wav').click(); await page.waitForTimeout(800);
  result.phases.clickA = { form: await form(), rows: { a: await rowInfo('a.wav') } };
  await shot('click-a-form');
  if (SCEN === 'E') {
    await waitNoToast(10000);
    phase = 'rescan';
    const n2 = (await ipcLog()).length;
    await page.getByRole('button', { name: /Rescan/ }).first().click();
    const reply = await waitLog((e) => e.channel === 'meta:read-batch' && e.phase === 'reply', n2, 10000);
    const rt = await watchToasts(2000);
    result.phases.rescan = { replied: !!reply, reply: reply?.values, toasts: rt, rows: { a: await rowInfo('a.wav'), b: await rowInfo('b.wav') } };
    await nameCell('a.wav').click(); await page.waitForTimeout(800);
    result.phases.rescan.form = await form();
    await shot('rescan-click-a-form');
  }
} catch (e) {
  result.error = String(e?.stack ?? e);
  await shot('error').catch(() => {});
}
result.ipc = await ipcLog().catch(() => []);
await app.close().catch(() => {});
result.pageErrors = pageErrors; result.toastsSeen = toastsSeen;
result.shaFinal = shas();
result.readersFinal = await readA();
const R = result.readersFinal;
const P = result.phases;
ok('setup Tags saved', !!P.setup?.toast);
ok('mid folder: list', SCEN === 'O' ? JSON.stringify(P.mid?.rows) === '["c.wav","d.wav"]' : P.mid?.rows?.length === 0, P.mid?.rows);
ok('mid folder: no toast', P.mid?.toasts?.length === 0, P.mid?.toasts);
ok('harness threw on read-batch', !!P.armed?.harnessThrew, P.armed?.thrownPaths);
ok('toast Failed to read 2 files', P.armed?.toast?.text === 'Failed to read 2 files', P.armed?.toast);
ok('a.wav Tagged after armed open', P.armed?.rows?.a?.tagged, P.armed?.rows);
ok('form Category after click a', P.clickA?.form?.category, P.clickA?.form);
if (SCEN === 'E') {
  ok('R: a.wav Tagged after rescan', P.rescan?.rows?.a?.tagged === true, P.rescan?.rows);
  ok('R: form Category=R30Cat', P.rescan?.form?.category === 'R30Cat', P.rescan?.form);
  ok('R: no error toast', !(P.rescan?.toasts ?? ['?']).some((x) => /Fail|error/i.test(x)), P.rescan?.toasts);
}
ok('sha unchanged by folder actions', JSON.stringify(result.shaAfterSetup) === JSON.stringify(result.shaFinal), { afterSetup: result.shaAfterSetup, final: result.shaFinal });
ok('readers ICAT=R30Cat after setup and final', result.readersAfterSetup?.ffICAT === 'R30Cat' && result.readersAfterSetup?.mmICAT === 'R30Cat' && R.ffICAT === 'R30Cat' && R.mmICAT === 'R30Cat', { setup: [result.readersAfterSetup?.ffICAT, result.readersAfterSetup?.mmICAT], final: [R.ffICAT, R.mmICAT] });
ok('pageErrors-empty', pageErrors.length === 0, pageErrors);
writeFileSync(join(OUT, `${TAG}.json`), JSON.stringify(result, null, 2));
console.log(LABEL, SCEN, JSON.stringify(Object.fromEntries(Object.entries(result.checks).map(([k, v]) => [k, [v.pass, v.detail]]))));
console.log('toastsSeen', JSON.stringify(toastsSeen));
if (result.error) console.log('ERROR', result.error);
