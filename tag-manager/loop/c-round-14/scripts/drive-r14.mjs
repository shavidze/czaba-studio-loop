import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { mkdtempSync, mkdirSync, copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const REPO = '/home/runner/czaba-project/czaba-tag-manager';
const OUT = '/home/runner/czaba-project/tmp/tag-manager-loop/c-round-14';
const req = createRequire(REPO + '/package.json');
const { _electron } = req('playwright');
const mm = await import(pathToFileURL(req.resolve('music-metadata')).href);
const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');
const work = mkdtempSync(join(tmpdir(), 'c-r14-smoke-'));
const dir = join(work, 'wavs'); mkdirSync(dir); const cfg = join(work, 'xdg'); mkdirSync(cfg);
const F = join(dir, 'smoke.wav'); copyFileSync(REPO + '/tests/fixtures/sample.wav', F);
const r = { work, sourceSha: sha(REPO + '/tests/fixtures/sample.wav'), before: sha(F) };
const app = await _electron.launch({ args: ['--no-sandbox', join(REPO, 'out/main/index.js')], env: { ...process.env, XDG_CONFIG_HOME: cfg } });
const page = await app.firstWindow();
await page.setViewportSize({ width: 1400, height: 900 });
await page.waitForLoadState('domcontentloaded');
await app.evaluate(({ dialog }, d) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [d] }); }, dir);
await page.waitForTimeout(800);
try {
  await page.getByText('Open Folder', { exact: true }).first().click();
  const cell = page.getByText('smoke.wav', { exact: true }).first();
  await cell.waitFor({ timeout: 15000 });
  await page.screenshot({ path: join(OUT, 'r14-6-1-scanned.png') });
  await cell.click(); await page.waitForTimeout(800);
  const input = page.locator('div.space-y-1', { has: page.locator('label', { hasText: /^Category \(UCS\)$/ }) }).locator('input').first();
  await input.click(); await input.fill('R14Cat'); await page.waitForTimeout(300);
  await page.screenshot({ path: join(OUT, 'r14-6-2-typed.png') });
  await page.getByRole('button', { name: /Save Tags/ }).first().click();
  const t = page.getByText(/Tags saved|failed|Failed|Error/).first(); await t.waitFor({ timeout: 10000 });
  r.toast = await t.textContent();
  await page.waitForTimeout(600);
  r.rowTagged = (await cell.locator('xpath=../..').getByText('Tagged', { exact: true }).count()) > 0;
  await page.screenshot({ path: join(OUT, 'r14-6-3-saved.png') });
} catch (e) { r.error = String(e); await page.screenshot({ path: join(OUT, 'r14-6-error.png') }); }
await app.close();
r.after = sha(F);
r.ffprobe = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format_tags', '-of', 'json', F]).toString()).format?.tags ?? {};
const m = await mm.parseFile(F);
r.mmExif = (m.native.exif ?? []).map((x) => [x.id, x.value]);
r.mmFormat = { container: m.format.container, sampleRate: m.format.sampleRate, duration: m.format.duration };
r.ICAT_ffprobe = r.ffprobe.ICAT ?? null; r.ICAT_mm = r.mmExif.filter(([k]) => k === 'ICAT').map(([, v]) => v);
writeFileSync(join(OUT, 'r14-6-result.json'), JSON.stringify(r, null, 2));
console.log(JSON.stringify(r, null, 2));
