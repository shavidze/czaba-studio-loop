import { createRequire } from 'node:module';
const req = createRequire('/home/runner/czaba-project/czaba-tag-manager/package.json');
const { _electron } = req('playwright');
const [repo, work, out] = process.argv.slice(2);
const app = await _electron.launch({ args: ['--no-sandbox', `${repo}/out/main/index.js`], env: { ...process.env, XDG_CONFIG_HOME: `${work}/xdg` } });
const page = await app.firstWindow();
await page.setViewportSize({ width: 1400, height: 900 });
await app.evaluate(({ dialog }, d) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [d] }); }, `${work}/wavs`);
await page.waitForTimeout(800);
await page.getByText('Open Folder', { exact: true }).click();
await page.getByText('nul-take.wav', { exact: true }).first().waitFor();
await page.waitForTimeout(1200);
await page.getByText('nul-take.wav', { exact: true }).first().click();
await page.waitForTimeout(800);
const take = page.locator('div.space-y-1', { has: page.locator('label', { hasText: /^Take$/ }) }).locator('input').first();
await take.scrollIntoViewIfNeeded();
console.log('Take', JSON.stringify(await take.inputValue()));
await page.screenshot({ path: out });
await app.close();
